"""Generate the comparator challenge from the roster sections of `Qsag/Top/*.lean`.

Each of `Top/Signing.lean`, `Top/Custody.lean` and `Top/Aggregation.lean` ends with a section
delimited by

    -- BEGIN COMPARATOR ROSTER
    -- END COMPARATOR ROSTER

holding restatements `Qsag.Top.<name>` of library theorems, each proved by citing the original
(`:=\n  _root_.Qsag.<original> <args>`). This script copies those statements into
`QsagChallenge.lean` with `by sorry` bodies and lists their names in `comparator.json`, so the
comparator checks that the solution's statements are exactly the challenge's and replays the
dependency closure. The remaining Top modules contribute declarations listed in TOP_THEOREMS.
The generated challenge also includes the public definitions needed to state those theorems.

    python3 lean/tools/gen_challenge.py           # rewrite QsagChallenge.lean and comparator.json
    python3 lean/tools/gen_challenge.py --check   # fail if either is stale
"""
import json
import re
import sys
from pathlib import Path

lean = Path(__file__).resolve().parents[1]
DOMAINS = ["Signing", "Custody", "Aggregation"]
BEGIN = "-- BEGIN COMPARATOR ROSTER\n"
END = "-- END COMPARATOR ROSTER\n"

# Modules whose definitions the roster statements mention. The challenge never imports `Qsag.Top`.
IMPORTS = [
    'Qsag.Math.Goldilocks',
    'Qsag.Math.Gf2Pow128',
    'Qsag.Oracle.Keccak',
    'Qsag.Oracle.Poseidon2',
    'Qsag.Protocol.Threshold.IdealTsig',
    'Qsag.Protocol.Credentials.ToprfSpdzArithmeticRefinement',
    'Qsag.Protocol.Aggregation.UcGames',
    'Qsag.Protocol.Threshold.MaliciousSecurity',
    'Qsag.Protocol.Threshold.Preprocessing',
    'Qsag.Protocol.Signing.HypertreeEufCma',
    'Qsag.Protocol.Threshold.ThresholdMpc',
    'Qsag.Protocol.Aggregation.Aggregation',
    'Qsag.Machine.ElfParse',
    'Qsag.Machine.ElfVerify',
    'Qsag.Machine.ElfFixtureVerify',
    'Qsag.Machine.McRefine',
    'Qsag.Exec.InteractiveUcEngine',
    'Qsag.Protocol.Migration.HdToprfAndMigrationSecurity',
    'Qsag.Protocol.Aggregation.CorduroyAndHemAirCompleteness',
    'Qsag.Exec.PosixCrashWal',
    'Qsag.Protocol.Threshold.BaggyAndRss256Security',
    'Qsag.Protocol.Signing.ProductionJortsBaggyBounds',
    'Qsag.Protocol.Aggregation.SuccinctWhirExtractorAndIdealAggregate',
    'Qsag.Protocol.Aggregation.ConcreteIvcDepth2Cert',
    'Qsag.Protocol.Aggregation.RecursiveIvcPublicRowQrom',
]

# These Top declarations state their types directly, outside the three legacy roster sections.
TOP_THEOREMS = {
    "Migration": ["production_curves_all_certified_prime", "settled_committed_witness_ownership", "zkHemV2_r1cs_migration_extract_or_qrom_128_break"],
    "Credentials": ["credential_sd_limbo256_tau33_interactive_soundness"],
    "ClosedProtocolReductions": ["zkHemV2_deployed_succinct_qrom_gameBound_128", "jorts_baggy_closed_euf_cma_spec_assumptions_bound"],
    "SecurityBounds": [],
    "DerivedSecuritySummary": [],
    "CustodyKeyHidingBound": ["thresholdServiceShared_prefixEquivalent_ideal"],
    "Foundations": ["threshold_three_projection_mac_blind_bound"],
    "ProbPkgGames": ["keyedRom_hiding_multiSession_gameBound"],
    "DistributedAuthRunBound": ["distributed_authRun_adaptive_unsafe_release_bound"],
    "CertCustodyAdaptiveBound": ["singletonTable_prfHard"],
}
DEFINITIONS = ["Qsag.Spec.GameBound", "Qsag.Spec.ValidAggregateWitness", "Qsag.Spec.aggregateWitnessCheck",
               "Qsag.Spec.ValidLegacyOwnership", "Qsag.Spec.verifiedAggregateMachine", "Qsag.Spec.aggregateRefinementGame"]
HEADER = """module
/- Generated by tools/gen_challenge.py. The challenge restates the public propositions
   and imports the definitions on which they depend. -/

"""

def direct_roster(domain, names):
    source = (lean / "Qsag" / "Top" / f"{domain}.lean").read_text()
    namespace = {"Foundations": "Qsag.Top.Foundations",
                 "DistributedAuthRunBound": "Qsag.DistributedAuthRun"}.get(domain, "Qsag.Top")
    blocks = ["namespace " + namespace]
    if domain == "DistributedAuthRunBound":
        blocks.extend(["open Spec KeyHidingCustody DistCustody", "set_option autoImplicit true",
                       source.split("section Probability\n")[1].split("theorem ")[0].strip()])
    elif domain == "ClosedProtocolReductions":
        start = source.index("section SuccinctWhir\n")
        stop = source.index("/-- **Closed Succinct-Transcript", start)
        blocks.extend([source[start:stop].strip(), "end SuccinctWhir"])
    elif domain == "CertCustodyAdaptiveBound":
        blocks.extend(["open Qsag.Spec", source.split("/-- One-entry function table.")[1].split("-/")[1].split("private theorem")[0].strip()])
    elif domain == "ProbPkgGames":
        blocks.append(source[source.index("abbrev keyedRomIface"):source.index("theorem keyedRomReal_eq")].strip())
    for name in names:
        start = re.search(r"^theorem " + re.escape(name) + r"\b", source, re.M).start()
        signature = re.split(r" :=(?: by)?\n  (?! )", source[start:], maxsplit=1)[0]
        blocks.append(signature + " := by sorry")
    blocks.append("end " + namespace)
    return blocks, [f"{namespace}.{name}" for name in names]

def roster_blocks(domain):
    text = (lean / "Qsag" / "Top" / f"{domain}.lean").read_text()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        raise SystemExit(f"Top/{domain}.lean: expected exactly one comparator roster section")
    body = text[text.index(BEGIN) + len(BEGIN): text.index(END)]
    blocks = [b for b in re.split(r"\n\s*\n", body.strip("\n")) if b.strip()]
    out = []
    for b in blocks:
        if b.lstrip().startswith("/-!"):
            out.append(("doc", None, b))
            continue
        m = re.search(r"^theorem (\S+)", b, re.M)
        cut = b.rfind(" :=\n  _root_.")
        if not m or cut < 0:
            raise SystemExit(f"Top/{domain}.lean: roster block is not a cited restatement:\n{b[:200]}")
        out.append(("thm", m.group(1), b[:cut] + " :=\n  by sorry"))
    return out


def generate():
    expected = set(DOMAINS) | set(TOP_THEOREMS)
    actual = {p.stem for p in (lean / "Qsag" / "Top").glob("*.lean")}
    if expected != actual:
        raise SystemExit(f"Top module roster mismatch: {sorted(expected ^ actual)}")
    names, parts = [], []
    for d in DOMAINS:
        parts.append(f"/-! # Roster of `Qsag.Top.{d}` -/")
        for kind, name, text in roster_blocks(d):
            parts.append(text)
            if kind == "thm":
                names.append(f"Qsag.Top.{name}")
    parts.append("end Qsag.Top")
    for domain, targets in TOP_THEOREMS.items():
        blocks, qualified = direct_roster(domain, targets)
        parts.extend(blocks)
        names.extend(qualified)
    imports = dict.fromkeys(IMPORTS)
    for domain in [*DOMAINS, *TOP_THEOREMS]:
        source = (lean / "Qsag" / "Top" / f"{domain}.lean").read_text()
        for module in re.findall(r"^public import (Qsag\.(?!Top\.)[\w.]+)$", source, re.M):
            imports[module] = None
    if len(set(names)) != len(names):
        raise SystemExit("duplicate roster theorem name")
    challenge = (HEADER + "\n".join(f"public import {m}" for m in imports) +
                 "\n\npublic section\nset_option warn.sorry false\nset_option autoImplicit false\nnamespace Qsag.Top\nopen Qsag CommRingOps Qsag.Aggregation Qsag.RustDurability\n\n" +
                 "\n\n".join(parts) + "\n")
    comparator = json.dumps({
        "challenge_module": "QsagChallenge",
        "solution_module": "Qsag",
        "theorem_names": names,
        "definition_names": DEFINITIONS,
        "permitted_axioms": ["propext", "Quot.sound"],
    }, indent=2) + "\n"
    return {"QsagChallenge.lean": challenge, "comparator.json": comparator}, names


outputs, names = generate()
stale = [n for n, c in outputs.items() if not (lean / n).exists() or (lean / n).read_text() != c]
if "--check" in sys.argv[1:]:
    if stale:
        raise SystemExit("Stale generated files: " + ", ".join(stale))
else:
    for n, c in outputs.items():
        (lean / n).write_text(c)
print(f"{len(names)} comparator roster theorems from Top/{{{','.join([*DOMAINS, *TOP_THEOREMS])}}}")
