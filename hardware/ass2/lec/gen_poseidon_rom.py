#!/usr/bin/env python3
"""Generate the ASS2 round ROM from crates/qsag-accel/src/poseidon2.rs."""
import re
import sys
from pathlib import Path

MASK = (1 << 64) - 1
PRIME = (1 << 64) - (1 << 32) + 1


def mix(x):
    x = (x + 0x9E3779B97F4A7C15) & MASK
    x = ((x ^ (x >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    x = ((x ^ (x >> 27)) * 0x94D049BB133111EB) & MASK
    return x ^ (x >> 31)


def main():
    rust = Path(sys.argv[1]).read_text()
    table = rust.split("pub const POSEIDON2_GL24_RC: [u64; 236] = [")[1].split("];")[0]
    words = [int(n, 16) for n in re.findall(r"0x[\da-fA-F_]+", table)]
    assert len(words) == 236
    for tag, rounds, lanes in [(0, 4, 12), (1, 22, 1), (2, 4, 12)]:
        for r in range(rounds):
            for lane in range(lanes):
                words.append(mix(mix(mix(0x504F53325F474C31 ^ tag) ^ r) ^ lane) % PRIME)
    assert len(words) == 354
    print("// Generated by gen_poseidon_rom.py. Width-12 constants start at 236.")
    print("module qsag_ass2_rc(input logic [8:0] addr, output logic [63:0] rc);")
    print("    always_comb case (addr)")
    for i, word in enumerate(words):
        print(f"        9'd{i}: rc = 64'h{word:016x};")
    print("        default: rc = '0;\n    endcase\nendmodule")


if __name__ == "__main__":
    main()
