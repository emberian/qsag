"""Assemble the resident image, resolve constant-pool offsets, and emit its synthesizable 4 KiB I-ROM."""
from pathlib import Path
import re
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "sim"))
sys.path.insert(0, str(root / "tools"))
from ass2_ref import assemble

CONSTS = [
    ("K_PUBID",    0x4449425550325341), # "AS2PUBID"
    ("K_P2DOM",    0x5153414757535450),
    ("K_AMASK",    0xfffc0ff00000f00c),
    ("K_CS_CODE0", 0x5341480100018801), # cSHAKE256("ASS2.CODE") prefix lane 0
    ("K_CS_CODE1", 0x0045444f432e3253), # cSHAKE256("ASS2.CODE") prefix lane 1
    ("K_CS_APP0",  0x5341580100018801), # cSHAKE256("ASS2.APPLET") prefix lane 0
    ("K_CS_APP1",  0x454c5050412e3253), # cSHAKE256("ASS2.APPLET") prefix lane 1
    ("K_APP_DOM0", 0x5050412e32535341), # "ASS2.APP"
]

def resolve_consts(src: str, base_off: int) -> str:
    offsets = {name: base_off + 8 * i for i, (name, _) in enumerate(CONSTS)}
    return re.sub(r"@(K_[A-Z0-9_]+)", lambda m: str(offsets[m.group(1)]), src)

def build():
    files = ("resident", "lifecycle", "fram", "signing")
    parts = {name: (root / "firmware" / (name + ".s")).read_text() for name in files}
    pool = "\n.align8\nrom_consts:\n" + "".join(f".word64 0x{val:016x}\n" for _, val in CONSTS)
    raw = parts["resident"] + pool + "\n" + "\n".join(parts[n] for n in files[1:])
    _, labels, _ = assemble(resolve_consts(raw, 480))
    base_off = labels["rom_consts"]
    assert base_off + 8 * (len(CONSTS) - 1) <= 1016, f"rom_consts too high for SLD64: {base_off}"
    image, labels, _ = assemble(resolve_consts(raw, base_off))
    if len(image) > 4096:
        raise ValueError(f"ROM overflow: {len(image)} bytes ({len(image)//4}/1024 words)")
    post_pc = labels["post_selftest"]
    assert 0 <= post_pc < 4096 and post_pc % 4 == 0, f"invalid post_selftest PC: {post_pc}"
    body = []
    for offset in range(0, len(image), 8):
        value = int.from_bytes(image[offset:offset+8], "little")
        if value:
            body.append(f"            9'd{offset//8}: rdata = 64'h{value:016x};")
    text = f"""// Generated by tools/build_rom.py from firmware/*.s.
// Pure combinational constant table (`0` flip-flops, `0` non-resettable `dffq_1` cells).
module qsag_ass2_irom (
    input logic [8:0] addr,
    output logic [63:0] rdata,
    output wire [11:0] post_pc_o
);
    assign post_pc_o = 12'd{post_pc};
    always_comb begin
        case (addr)
""" + "\n".join(body) + """
            default: rdata = 64'd0;
        endcase
    end
endmodule
"""
    path = root / "rtl/qsag_ass2_irom.sv"
    if "--check" in sys.argv:
        assert path.read_text() == text, "resident image is stale"
    else:
        path.write_text(text)
    print(f"resident image: {len(image)//4}/1024 words ({len(image)}/4096 bytes), post_selftest @ 0x{post_pc:03x}")

if __name__ == "__main__":
    build()
