#!/usr/bin/env python3
"""Generate rtl/dregg_defs.svh from the model's isa.py and units.py.

    python3 gen_defs.py [--scratch N] [--check] <out.svh>

The header is `included inside module bodies (localparams only; no package, so that Yosys, Verilator
and LibreLane read it the same way). Every constant comes from the model: operation numbers, function
tables, the register-file row map, the hardwired address ranges, error codes and unit clock counts.

--scratch N   build the row map with N scratch rows. The model has 12 (64 rows); the specification's
              configuration S has 20 (72 rows, ARCHITECTURE.md 5.2). The checked-in header is the
              72-row map. model_isa() below loads isa.py with that one number replaced, so the model
              and the RTL can be run on the same map without editing the model.
--check       compare with the existing file instead of writing it; exit 1 if it differs.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODEL = os.path.normpath(os.path.join(HERE, "..", "model"))


def model_isa(scratch=None):
    """Import the model's isa module, optionally with another scratch-row count. Must be called
    before anything else imports isa. Returns the module."""
    import importlib.util
    path = os.path.join(MODEL, "isa.py")
    with open(path) as fh:
        src = fh.read()
    if scratch is not None:
        m = re.search(r"^N_LANES, N_KWORK, N_SCRATCH, N_KEYS, N_PINS, N_STATE, N_OUT = (\d+), (\d+), (\d+), ", src, re.M)
        if not m:
            raise SystemExit("gen_defs: the row-count line of isa.py changed shape")
        if int(m.group(3)) != scratch:
            src = src[:m.start(3)] + str(scratch) + src[m.end(3):]
    spec = importlib.util.spec_from_loader("isa", loader=None, origin=path)
    mod = importlib.util.module_from_spec(spec)
    mod.__file__ = path
    exec(compile(src, path, "exec"), mod.__dict__)
    sys.modules["isa"] = mod
    if MODEL not in sys.path:
        sys.path.insert(0, MODEL)
    return mod


def render(isa, units):
    o = []
    p = o.append
    p("// Generated by v2/rtl/gen_defs.py from v2/model/isa.py and units.py. Do not edit.")
    p("// `include this file inside a module body.")
    p("/* verilator lint_off UNUSEDPARAM */")
    p(f"localparam int UW = {isa.WIDTH};")
    for i, n in enumerate(isa.OPS):
        p(f"localparam logic [4:0] OP_{n} = 5'd{i};")
    for i, n in enumerate(isa.UN):
        p(f"localparam logic [6:0] UN_{n} = 7'd{i};")
    p(f"localparam int N_UN = {len(isa.UN)};")
    for i, n in enumerate(isa.CTL):
        p(f"localparam logic [6:0] CTL_{n} = 7'd{i};")
    p(f"localparam int N_CTL = {len(isa.CTL)};")
    for i, n in enumerate(isa.LDF):
        p(f"localparam logic [6:0] LDF_{n} = 7'd{i};")
    p(f"localparam int N_LDF = {len(isa.LDF)};")
    for i, n in enumerate(isa.FRAM):
        p(f"localparam logic [6:0] FRF_{n} = 7'd{i};")
    p(f"localparam int N_FRAM = {len(isa.FRAM)};")
    for i, n in enumerate(isa.COND):
        p(f"localparam logic [6:0] COND_{n} = 7'd{i};")
    p(f"localparam int N_COND = {len(isa.COND)};")
    p(f"localparam int W_LANES_LO_B = {isa.W_LANES_LO.bit_length() - 1};")
    p(f"localparam int W_LANES_HI_B = {isa.W_LANES_HI.bit_length() - 1};")
    p(f"localparam int W_SCRATCH_B = {isa.W_SCRATCH.bit_length() - 1};")
    p(f"localparam int W_OUT_B = {isa.W_OUT.bit_length() - 1};")
    p("// hardwired sequencer constants")
    p(f"localparam logic [10:0] IDLE_ADDR = 11'd{isa.IDLE_ADDR};")
    p(f"localparam logic [10:0] KEY_LO = 11'd{isa.KEY_LO};")
    p(f"localparam logic [10:0] KEY_HI = 11'd{isa.KEY_HI};")
    p(f"localparam logic [10:0] REC_LO = 11'd{isa.REC_LO};")
    p(f"localparam logic [10:0] REC_HI = 11'd{isa.REC_HI};")
    p(f"localparam int END_CLOCKS = {isa.END_CLOCKS};")
    for n in ("D_DIAG", "D_PROV", "D_KEYED"):
        p(f"localparam logic [1:0] {n} = 2'd{getattr(isa, n)};")
    for n in ("E_MAGIC", "E_OPCODE", "E_LEN", "E_NOKEY", "E_KEYSET"):
        p(f"localparam logic [15:0] {n} = 16'd{getattr(isa, n)};")
    p("// register-file row map")
    for n in ("N_LANES", "N_KWORK", "N_SCRATCH", "N_KEYS", "N_PINS", "N_STATE", "N_OUT", "LANE0", "KWORK0", "SCRATCH0",
              "KEY0", "PIN0", "STATE0", "OUT0", "RATE_LANES"):
        p(f"localparam int {n} = {getattr(isa, n)};")
    p(f"localparam int NROWS = {isa.ROWS_S};")
    p("localparam int N_KDEV = 4;   // key rows the boot interface loads (machine.py power_on)")
    assert len(isa.FRAM_SRC) == 3
    for i, r in enumerate(isa.FRAM_SRC):
        p(f"localparam logic [6:0] FRAM_SRC{i} = 7'd{r};")
    # wipe class of each row, as regfile.py wipe() has it
    lo = [r for r in range(0, 8)]
    hi = [r for r in range(8, isa.SCRATCH0)]
    p(f"localparam int WIPE_LO_LAST = {lo[-1]};      // W_LANES_LO: rows 0..{lo[-1]}")
    p(f"localparam int WIPE_HI_LAST = {hi[-1]};     // W_LANES_HI: rows {hi[0]}..{hi[-1]} (lanes and the Keccak work rows)")
    p("// unit clock counts (units.py)")
    p(f"localparam int KECCAK_F = {units.KECCAK_F};")
    p(f"localparam int KECCAK_P12 = {units.KECCAK_P12};")
    p(f"localparam logic [3:0] FRAM_DIV = 4'd{units.FRAM_DIV};")
    for n in ("FRAM_RSTART", "FRAM_WSTART", "FRAM_WORD", "FRAM_DONE", "NONCE_DRAW", "AUTH_VERIFY"):
        p(f"localparam int T_{n} = {getattr(units, n)};")
    import machine
    p(f"localparam int MAX_STEPS = {machine.Machine.MAX_STEPS};   // instructions per command (machine.py)")
    p("/* verilator lint_on UNUSEDPARAM */")
    return "\n".join(o) + "\n"


def main():
    args = sys.argv[1:]
    scratch, check = None, False
    while args and args[0].startswith("--"):
        a = args.pop(0)
        if a == "--scratch":
            scratch = int(args.pop(0))
        elif a == "--check":
            check = True
        else:
            raise SystemExit(__doc__)
    if len(args) != 1:
        raise SystemExit(__doc__)
    isa = model_isa(scratch)
    import units
    text = render(isa, units)
    if check:
        with open(args[0]) as fh:
            if fh.read() != text:
                print(f"gen_defs: {args[0]} is stale against the model")
                sys.exit(1)
        return
    with open(args[0], "w") as fh:
        fh.write(text)


if __name__ == "__main__":
    main()
