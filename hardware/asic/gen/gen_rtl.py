#!/usr/bin/env python3
"""Emit the generated QSAG-NI RTL:
  * 3-way 32x32 / 33x33 Solinas-Karatsuba Dadda partial-product tree (`2 x tree32 + 1 x tree33`,
    every stage <= 4 CSA rows) and direct Golden-Ratio modular CSA fold
    `a*b == (1 - 2^32)*P0 + 2^32*PS - P2 (mod p)` (`sk_p0`, `sk_ps`, `sk_a`, `sk_b`, `sk_s2`)
  * Standalone 128->64 CSA reducer (`fold_one` + `final_par`) matching Obend `goldilocksReduce128`
  * Hierarchical CSE Poseidon2 `M_E` (`csa4 + 4 x m4_lane`, `csa3 + 3 x me_col_lane`) & `M_I`
    (`2 x csa3 + sum4_csa` tail + `12 parameterized mi_lane instances`)
  * Canopy feed-forward, Poseidon2 round constants, and balanced-XOR-tree GF(2^128) Wiedemann `T_7` maps

The generated carry-save networks are also checked against their integer or modulo-p
weights by lec/check_csa.py.

  python3 gen/gen_rtl.py rtl/
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from csagen import Mod, Csa, final, P
import qsag_ref as ref

HDR = "// GENERATED by hardware/asic/gen/gen_rtl.py. Do not edit; regenerate.\n`default_nettype none\n"
FTR = "`default_nettype wire\n"
stats = {}


def _assign_rows(mod, csa, w_out, s_name="s", c_name="c"):
    csa.compress()
    xs = [csa.cols[w][0] if len(csa.cols.get(w, [])) > 0 else "1'b0" for w in range(w_out)]
    ys = [csa.cols[w][1] if len(csa.cols.get(w, [])) > 1 else "1'b0" for w in range(w_out)]
    mod.raw(f"assign {s_name} = {{{', '.join(reversed(xs))}}};")
    mod.raw(f"assign {c_name} = {{{', '.join(reversed(ys))}}};")


def _gen_sub_tree(tag, wa, has_top_bit=False):
    """Emit a 32x32 (`wa=32`) or 33x33 (`wa=33, has_top_bit=True`) 4-row-per-stage Dadda tree."""
    mods = []
    w_slice = wa + 4
    ms = Mod(f"qsag_gl64_mul_slice{wa}x4", [
        f"input  wire [{wa - 1}:0] a",
        "input  wire [3:0]  b",
        f"output wire [{w_slice - 1}:0] s",
        f"output wire [{w_slice - 1}:0] c",
    ])
    csa_s = Csa(ms)
    for i in range(wa):
        for j in range(4):
            csa_s.raw(ms.w(f"a[{i}] & b[{j}]"), i + j)
    _assign_rows(ms, csa_s, w_slice)
    mods.append(ms.text())
    stats[f"mul_slice{wa}x4 (fa, ha, stages)"] = (csa_s.fas, csa_s.has, csa_s.stages)

    tot_fa = 8 * csa_s.fas
    levels = [
        (1, wa + 4,  4,  wa + 8,  4),
        (2, wa + 8,  8,  wa + 16, 2),
        (3, wa + 16, 16, wa + 32, 1),
    ]
    for lvl, win, sh, wout, count in levels:
        mc = Mod(f"qsag_gl64_mul_comb{wa}_l{lvl}", [
            f"input  wire [{win - 1}:0] s0",
            f"input  wire [{win - 1}:0] c0",
            f"input  wire [{win - 1}:0] s1",
            f"input  wire [{win - 1}:0] c1",
            f"output wire [{wout - 1}:0] s",
            f"output wire [{wout - 1}:0] c",
        ])
        cc = Csa(mc)
        for b in range(win):
            cc.raw(f"s0[{b}]", b)
            cc.raw(f"c0[{b}]", b)
            if b + sh < wout:
                cc.raw(f"s1[{b}]", b + sh)
                cc.raw(f"c1[{b}]", b + sh)
        _assign_rows(mc, cc, wout)
        mods.append(mc.text())
        tot_fa += count * cc.fas

    w_final = 2 * wa
    if has_top_bit:
        mt = Mod(f"qsag_gl64_mul_comb{wa}_top", [
            f"input  wire [{wa + 31}:0] s0",
            f"input  wire [{wa + 31}:0] c0",
            f"input  wire [{wa - 1}:0]  a",
            "input  wire [0:0]  b_hi",
            f"output wire [{w_final - 1}:0] s",
            f"output wire [{w_final - 1}:0] c",
        ])
        ct = Csa(mt)
        for b in range(wa + 32):
            ct.raw(f"s0[{b}]", b)
            ct.raw(f"c0[{b}]", b)
        for i in range(wa):
            ct.raw(mt.w(f"a[{i}] & b_hi[0]"), 32 + i)
        _assign_rows(mt, ct, w_final)
        mods.append(mt.text())
        tot_fa += ct.fas

    wb = wa if has_top_bit else 32
    top = [
        f"module {tag} (",
        f"  input  wire [{wa - 1}:0] a,",
        f"  input  wire [{wb - 1}:0] b,",
        f"  output wire [{w_final - 1}:0] s,",
        f"  output wire [{w_final - 1}:0] c",
        ");",
    ]
    for k in range(8):
        top.append(f"  wire [{w_slice - 1}:0] l0_s{k}, l0_c{k};")
        top.append(f"  qsag_gl64_mul_slice{wa}x4 u_s{k} (.a(a), .b(b[{4*k+3}:{4*k}]), .s(l0_s{k}), .c(l0_c{k}));")
    for lvl, win, sh, wout, count in levels:
        prev = f"l{lvl - 1}"
        cur = f"l{lvl}"
        for k in range(count):
            if lvl < 3 or has_top_bit:
                top.append(f"  wire [{wout - 1}:0] {cur}_s{k}, {cur}_c{k};")
                so, co = f"{cur}_s{k}", f"{cur}_c{k}"
            else:
                so, co = "s", "c"
            top.append(
                f"  qsag_gl64_mul_comb{wa}_l{lvl} u_l{lvl}_{k} ("
                f".s0({prev}_s{2*k}), .c0({prev}_c{2*k}), "
                f".s1({prev}_s{2*k+1}), .c1({prev}_c{2*k+1}), .s({so}), .c({co}));"
            )
    if has_top_bit:
        top.append(f"  qsag_gl64_mul_comb{wa}_top u_top (.s0(l3_s0), .c0(l3_c0), .a(a), .b_hi(b[32:32]), .s(s), .c(c));")
    top.append("endmodule\n")
    return "\n".join(mods) + "\n" + "\n".join(top), tot_fa


def gen_mul_tree():
    """3-way Solinas-Karatsuba partial-product trees (`2 x 32x32 + 1 x 33x33`)."""
    t32_txt, fa32 = _gen_sub_tree("qsag_gl64_mul_tree32", 32, has_top_bit=False)
    t33_txt, fa33 = _gen_sub_tree("qsag_gl64_mul_tree33", 33, has_top_bit=True)
    stats["mul_tree_sk_total_fa"] = 2 * fa32 + fa33
    wrap = """module qsag_gl64_mul_tree (
  input  wire [63:0] a,
  input  wire [63:0] b,
  output wire [63:0] p0_s,
  output wire [63:0] p0_c,
  output wire [63:0] p2_s,
  output wire [63:0] p2_c,
  output wire [65:0] ps_s,
  output wire [65:0] ps_c
);
  wire [32:0] sa = {1'b0, a[31:0]} + {1'b0, a[63:32]};
  wire [32:0] sb = {1'b0, b[31:0]} + {1'b0, b[63:32]};
  qsag_gl64_mul_tree32 u_p0 (.a(a[31:0]),  .b(b[31:0]),  .s(p0_s), .c(p0_c));
  qsag_gl64_mul_tree32 u_p2 (.a(a[63:32]), .b(b[63:32]), .s(p2_s), .c(p2_c));
  qsag_gl64_mul_tree33 u_ps (.a(sa),       .b(sb),       .s(ps_s), .c(ps_c));
endmodule
"""
    return t32_txt + "\n" + t33_txt + "\n" + wrap


def gen_fold():
    """Direct Solinas-Karatsuba modular CSA fold:
      (a0 + 2^32*a1)*(b0 + 2^32*b1) == (P0 - P2) + 2^32*(PS - P0) (mod p),
    factored into pure exact 4:2 integer compressors (`sk_c0`, `sk_c1`, `sk_m0`, `sk_m1`, <= 134 FAs
    each -> < 1s LEC) and tiny <=138-bit modulo-p leaves (`sk_sh32`: 68b/32 FAs; `sk_s2`: 138b/77 FAs
    with exact `+6` bias cancelling `2*(1 + 2^32)*(2^64 - 1) == -6 (mod p)`), plus standalone
    `fold_one` + `reduce128_csa` for Obend/KATs.
    """
    m1 = Mod("qsag_gl64_fold_one", [
        "input  wire [127:0] v",
        "output wire [W1-1:0] x",
        "output wire [W1-1:0] y",
    ])
    c1 = Csa(m1)
    c1.term("v", 128)
    x1, y1, w1, q1 = c1.rows("r", None)
    m1.raw(f"assign x = {x1};")
    m1.raw(f"assign y = {y1};")
    m1.ports[1] = f"output wire [{w1 - 1}:0] x"
    m1.ports[2] = f"output wire [{w1 - 1}:0] y"
    stats["fold_one (W1, q1, fa)"] = (w1, q1, c1.fas)

    # 1) `qsag_gl64_sk_c0`: exact 4:2 integer sum d0x + d0y == p0_s + p0_c + ~p2_s + ~p2_c
    mc0 = Mod("qsag_gl64_sk_c0", [
        "input  wire [63:0] p0_s",
        "input  wire [63:0] p0_c",
        "input  wire [63:0] p2_s",
        "input  wire [63:0] p2_c",
        "output wire [65:0] d0x",
        "output wire [65:0] d0y",
    ])
    cc0 = Csa(mc0)
    cc0.term_exact("p0_s", 64, 0, 1)
    cc0.term_exact("p0_c", 64, 0, 1)
    cc0.term_exact("p2_s", 64, 0, -1)
    cc0.term_exact("p2_c", 64, 0, -1)
    cc0.const = 0
    _assign_rows(mc0, cc0, 66, "d0x", "d0y")

    # 2) `qsag_gl64_sk_c1`: exact 4:2 integer sum d1x + d1y == ps_s + ps_c + ~p0_s + ~p0_c
    mc1 = Mod("qsag_gl64_sk_c1", [
        "input  wire [65:0] ps_s",
        "input  wire [65:0] ps_c",
        "input  wire [63:0] p0_s",
        "input  wire [63:0] p0_c",
        "output wire [67:0] d1x",
        "output wire [67:0] d1y",
    ])
    cc1 = Csa(mc1)
    cc1.term_exact("ps_s", 66, 0, 1)
    cc1.term_exact("ps_c", 66, 0, 1)
    cc1.term_exact("p0_s", 64, 0, -1)
    cc1.term_exact("p0_c", 64, 0, -1)
    cc1.const = 0
    _assign_rows(mc1, cc1, 68, "d1x", "d1y")

    # 3) `qsag_gl64_sk_sh32` (68 input bits, 32 FAs): (x + y) == (v * 2^32) (mod p)
    msh = Mod("qsag_gl64_sk_sh32", [
        "input  wire [67:0] v",
        "output wire [WSH-1:0] x",
        "output wire [WSH-1:0] y",
    ])
    csh = Csa(msh)
    csh.term("v", 68, 32, 1)
    xsh, ysh, wsh, _ = csh.rows("r", None)
    msh.raw(f"assign x = {xsh};")
    msh.raw(f"assign y = {ysh};")
    msh.ports[1] = f"output wire [{wsh - 1}:0] x"
    msh.ports[2] = f"output wire [{wsh - 1}:0] y"

    # 4) `qsag_gl64_sk_m0`: exact 4:2 integer sum m0x + m0y == d0x + d0y + e1x + e1y
    mm0 = Mod("qsag_gl64_sk_m0", [
        "input  wire [65:0] d0x",
        "input  wire [65:0] d0y",
        f"input  wire [{wsh - 1}:0] e1x",
        f"input  wire [{wsh - 1}:0] e1y",
        "output wire [67:0] m0x",
        "output wire [67:0] m0y",
    ])
    cm0 = Csa(mm0)
    cm0.term_exact("d0x", 66)
    cm0.term_exact("d0y", 66)
    cm0.term_exact("e1x", wsh)
    cm0.term_exact("e1y", wsh)
    _assign_rows(mm0, cm0, 68, "m0x", "m0y")

    # 5) `qsag_gl64_sk_m1`: exact 4:2 integer sum m1x + m1y == m0x + m0y + e2x + e2y
    mm1 = Mod("qsag_gl64_sk_m1", [
        "input  wire [67:0] m0x",
        "input  wire [67:0] m0y",
        f"input  wire [{wsh - 1}:0] e2x",
        f"input  wire [{wsh - 1}:0] e2y",
        "output wire [68:0] m1x",
        "output wire [68:0] m1y",
    ])
    cm1 = Csa(mm1)
    cm1.term_exact("m0x", 68)
    cm1.term_exact("m0y", 68)
    cm1.term_exact("e2x", wsh)
    cm1.term_exact("e2y", wsh)
    _assign_rows(mm1, cm1, 69, "m1x", "m1y")

    # 6) `qsag_gl64_sk_s2` (138 input bits -> max_quot = 3): m1x + m1y + 6 -> (x, y) < 4*p
    m2 = Mod("qsag_gl64_sk_s2", [
        "input  wire [68:0] bx",
        "input  wire [68:0] by",
        "output wire [FW-1:0] x",
        "output wire [FW-1:0] y",
    ])
    c2 = Csa(m2)
    c2.term("bx", 69, 0, 1)
    c2.term("by", 69, 0, 1)
    c2.const += 6  # cancels 2*(1 + 2^32)*(2^64 - 1) == -6 (mod p)
    x2, y2, fw, fq = c2.rows("r", 3)
    m2.raw(f"assign x = {x2};")
    m2.raw(f"assign y = {y2};")
    m2.ports[2] = f"output wire [{fw - 1}:0] x"
    m2.ports[3] = f"output wire [{fw - 1}:0] y"
    stats["sk_fold (wsh, fw, fq, fa)"] = (
        wsh, fw, fq, cc0.fas + cc1.fas + 2 * csh.fas + cm0.fas + cm1.fas + c2.fas
    )

    wrap = f"""module qsag_gl64_fold (
  input  wire [63:0] p0_s,
  input  wire [63:0] p0_c,
  input  wire [63:0] p2_s,
  input  wire [63:0] p2_c,
  input  wire [65:0] ps_s,
  input  wire [65:0] ps_c,
  output wire [{fw - 1}:0] x,
  output wire [{fw - 1}:0] y
);
  wire [65:0] d0x, d0y;
  wire [67:0] d1x, d1y, m0x, m0y;
  wire [{wsh - 1}:0] e1x, e1y, e2x, e2y;
  wire [68:0] m1x, m1y;
  qsag_gl64_sk_c0   u_c0 (.p0_s(p0_s), .p0_c(p0_c), .p2_s(p2_s), .p2_c(p2_c), .d0x(d0x), .d0y(d0y));
  qsag_gl64_sk_c1   u_c1 (.ps_s(ps_s), .ps_c(ps_c), .p0_s(p0_s), .p0_c(p0_c), .d1x(d1x), .d1y(d1y));
  qsag_gl64_sk_sh32 u_e1 (.v(d1x), .x(e1x), .y(e1y));
  qsag_gl64_sk_sh32 u_e2 (.v(d1y), .x(e2x), .y(e2y));
  qsag_gl64_sk_m0   u_m0 (.d0x(d0x), .d0y(d0y), .e1x(e1x), .e1y(e1y), .m0x(m0x), .m0y(m0y));
  qsag_gl64_sk_m1   u_m1 (.m0x(m0x), .m0y(m0y), .e2x(e2x), .e2y(e2y), .m1x(m1x), .m1y(m1y));
  qsag_gl64_sk_s2   u_s2 (.bx(m1x), .by(m1y), .x(x), .y(y));
endmodule
"""
    red = f"""module qsag_gl64_reduce128_csa (
  input  wire [127:0] v,
  output wire [63:0]  r
);
  wire [{w1 - 1}:0] x, y;
  qsag_gl64_fold_one u_f (.v(v), .x(x), .y(y));
  qsag_gl64_final_par #(.W({w1}), .NJ({q1 + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""
    return (
        "\n".join([m1.text(), mc0.text(), mc1.text(), msh.text(), mm0.text(), mm1.text(), m2.text(), wrap]),
        red, w1, q1, wsh, fw, fq
    )


def gen_mul(fw, fq):
    return f"""module qsag_gl64_mul_csa (
  input  wire [63:0] a,
  input  wire [63:0] b,
  output wire [63:0] r
);
  wire [63:0] p0_s, p0_c, p2_s, p2_c;
  wire [65:0] ps_s, ps_c;
  wire [{fw - 1}:0] x, y;
  qsag_gl64_mul_tree u_tree (
    .a(a), .b(b),
    .p0_s(p0_s), .p0_c(p0_c),
    .p2_s(p2_s), .p2_c(p2_c),
    .ps_s(ps_s), .ps_c(ps_c)
  );
  qsag_gl64_fold u_fold (
    .p0_s(p0_s), .p0_c(p0_c),
    .p2_s(p2_s), .p2_c(p2_c),
    .ps_s(ps_s), .ps_c(ps_c),
    .x(x), .y(y)
  );
  qsag_gl64_final_par #(.W({fw}), .NJ({fq + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""


def _emit_lin_mod(name, terms):
    """Emit a small <=4-row linear-combination module `r = (sum_k wt_k * (in_k : W_k)) mod p`."""
    ports = [f"input  wire [{w_in - 1}:0] {sig}" for sig, w_in, _, _ in terms] + ["output wire [63:0] r"]
    m = Mod(name, ports)
    c = Csa(m)
    rows = 0
    for sig, w_in, sh, wt in terms:
        if abs(wt) == 7:
            c.term_exact(sig, w_in, sh + 3, 1 if wt > 0 else -1)
            c.term_exact(sig, w_in, sh, -1 if wt > 0 else 1)
            rows += 2
        elif wt != 0:
            c.term_exact(sig, w_in, sh, wt)
            rows += 1
    assert rows <= 4, f"{name} has {rows} CSA rows (> 4)"
    x, y, w, q = c.rows("o_", None)
    final(m, "u_f", x, y, w, q, "r", False)
    return m.text(), c.fas


def gen_csa_helpers():
    """Pure carry-save 3:2 and 4:2 word compressors (`sx + sy == sum(inputs)` with 0 final adders)."""
    m3 = Mod("qsag_gl_csa3_66", [
        "input  wire [63:0] a0",
        "input  wire [63:0] a1",
        "input  wire [63:0] a2",
        "output wire [65:0] sx",
        "output wire [65:0] sy",
    ])
    c3 = Csa(m3)
    for k in range(3):
        c3.term_exact(f"a{k}", 64)
    _assign_rows(m3, c3, 66, "sx", "sy")

    m4 = Mod("qsag_gl_csa4_66", [
        "input  wire [63:0] a0",
        "input  wire [63:0] a1",
        "input  wire [63:0] a2",
        "input  wire [63:0] a3",
        "output wire [65:0] sx",
        "output wire [65:0] sy",
    ])
    c4 = Csa(m4)
    for k in range(4):
        c4.term_exact(f"a{k}", 64)
    _assign_rows(m4, c4, 66, "sx", "sy")
    return m3.text() + "\n" + m4.text(), c3.fas, c4.fas


def gen_me(fa_csa3, fa_csa4):
    """Hierarchical CSE M_E with <=4-row leaf modules."""
    m4_lane, fa_m4l = _emit_lin_mod("qsag_p2_m4_lane", [
        ("sx", 66, 0, 1), ("sy", 66, 0, 1), ("bi", 64, 0, 1), ("bj", 64, 1, 1)
    ])
    me_lane, fa_mel = _emit_lin_mod("qsag_p2_me_col_lane", [
        ("sx", 66, 0, 1), ("sy", 66, 0, 1), ("yb", 64, 0, 1), ("rcb", 64, 0, 1)
    ])
    stats["me_total_fa"] = 3 * (fa_csa4 + 4 * fa_m4l) + 4 * (fa_csa3 + 3 * fa_mel)

    layer = """module qsag_p2_me (
  input wire [767:0] x, rc,
  output wire [767:0] y
);
  wire [63:0] mixed [3][4];
  for (genvar block=0; block<3; block++) begin : g_block
    wire [63:0] b [4];
    wire [65:0] sx, sy;
    qsag_gl_csa4_66 sum (.a0(b[0]), .a1(b[1]), .a2(b[2]), .a3(b[3]), .sx, .sy);
    for (genvar i=0; i<4; i++) begin : g_lane
      assign b[i] = x[64*(3*i+block) +:64];
      qsag_p2_m4_lane lane (.sx, .sy, .bi(b[i]), .bj(b[(i+1)%4]), .r(mixed[block][i]));
    end
  end
  for (genvar i=0; i<4; i++) begin : g_col
    wire [65:0] sx, sy;
    qsag_gl_csa3_66 sum (.a0(mixed[0][i]), .a1(mixed[1][i]), .a2(mixed[2][i]), .sx, .sy);
    for (genvar b=0; b<3; b++) begin : g_lane
      qsag_p2_me_col_lane lane (.sx, .sy, .yb(mixed[b][i]), .rcb(rc[64*(3*i+b) +:64]), .r(y[64*(3*i+b) +:64]));
    end
  end
endmodule
"""
    return "\n".join([m4_lane, me_lane, layer])


def gen_mi(fa_csa3):
    """Hierarchical CSE M_I with <=4-row leaf modules."""
    sum4_csa, fa_s4 = _emit_lin_mod("qsag_p2_sum4_csa", [
        ("sx0", 66, 0, 1), ("sy0", 66, 0, 1), ("sx1", 66, 0, 1), ("sy1", 66, 0, 1)
    ])
    tail = """module qsag_p2_mi_tail (input wire [703:0] x_hi, output wire [63:0] s_tail);
  wire [767:0] padded = {64'd0, x_hi};
  wire [63:0] part [2];
  for (genvar half=0; half<2; half++) begin : g_half
    wire [65:0] sx [2], sy [2];
    for (genvar g=0; g<2; g++) begin : g_sum
      localparam int OFFSET = 64*(6*half+3*g);
      qsag_gl_csa3_66 sum (.a0(padded[OFFSET +:64]), .a1(padded[OFFSET+64 +:64]),
                           .a2(padded[OFFSET+128 +:64]), .sx(sx[g]), .sy(sy[g]));
    end
    qsag_p2_sum4_csa combine (.sx0(sx[0]), .sy0(sy[0]), .sx1(sx[1]), .sy1(sy[1]), .r(part[half]));
  end
  qsag_gl64_addsub add (.a(part[0]), .b(part[1]), .sub(1'b0), .r(s_tail));
endmodule
"""
    lanes = []
    tot_fa = 2 * (2 * fa_csa3 + fa_s4)
    for l in range(12):
        ml = Mod("lane", [])
        cl = Csa(ml)
        cl.term_exact("s_tail", 64)
        cl.term_exact("rcl", 64)
        if l == 0:
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("x0", 64, 6, -1)
        else:
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("xl", 64, l - 1, 1)
        lx, ly, lw, lq = cl.rows("o_", None)
        final(ml, "u_f", lx, ly, lw, lq, "y", False)
        tot_fa += cl.fas
        lanes.append(f"  if (LANE == {l}) begin : g_lane{l}")
        lanes.extend(ml.lines)
        if l == 0:
            lanes.append("    wire unused_xl = ^xl;")
        lanes.append("  end")
    stats["mi_total_fa"] = tot_fa

    lane = ("module qsag_p2_mi_lane #(parameter int LANE=0) "
            "(input wire [63:0] x0, xl, s_tail, rcl, output wire [63:0] y);\n"
            + "\n".join(lanes) + "\nendmodule\n")
    app = """module qsag_p2_mi_apply (
  input wire [63:0] x0, input wire [703:0] x_hi, input wire [63:0] s_tail,
  input wire [767:0] rc, output wire [767:0] y
);
  wire [767:0] x = {x_hi, x0};
  for (genvar l=0; l<12; l++) begin : g_lane
    qsag_p2_mi_lane #(.LANE(l)) lane (.x0, .xl(x[64*l +:64]), .s_tail, .rcl(rc[64*l +:64]), .y(y[64*l +:64]));
  end
endmodule
"""
    wrap = """module qsag_p2_mi (
  input  wire [767:0] x,
  input  wire [767:0] rc,
  output wire [767:0] y
);
  wire [63:0] s_tail;
  qsag_p2_mi_tail  u_tail  (.x_hi(x[767:64]), .s_tail(s_tail));
  qsag_p2_mi_apply u_apply (.x0(x[63:0]), .x_hi(x[767:64]), .s_tail(s_tail), .rc(rc), .y(y));
endmodule
"""
    return "\n".join([sum4_csa, tail, lane, app, wrap])


def gen_canopy_ff():
    """ff_i = l_i + 2 r_i + 4 c_i (mod p), i < 4; l = st[0..3], r = st[4..7], c = st[8..11]."""
    m1 = Mod("lane", [])
    csa = Csa(m1)
    csa.term_exact("l", 64, 0)
    csa.term_exact("r", 64, 1)
    csa.term_exact("c", 64, 2)
    x, y, w, q = csa.rows("o_", None)
    final(m1, "u_f", x, y, w, q, "result", False)

    return ("module qsag_p2_canopy_ff (input wire [767:0] x, output wire [255:0] ff);\n"
            "  for (genvar i=0; i<4; i++) begin : g_lane\n"
            "    wire [63:0] l=x[64*i+:64], r=x[64*(4+i)+:64], c=x[64*(8+i)+:64];\n"
            "    wire [63:0] result;\n" + "\n".join(m1.lines) +
            "\n    assign ff[64*i+:64] = result;\n  end\nendmodule\n")


def gen_rc():
    """slot n = constants added by the linear layer that precedes S-box layer n (slot 30: none)."""
    slots = []
    for r in range(4):
        slots.append([ref.p2_rc(0, r, l) for l in range(12)])
    for r in range(22):
        slots.append([ref.p2_rc(1, r, 0)] + [0] * 11)
    for r in range(4):
        slots.append([ref.p2_rc(2, r, l) for l in range(12)])
    slots.append([0] * 12)
    out = ["module qsag_p2_rc (", "  input  wire [4:0] slot,", "  output reg  [767:0] rc", ");",
           "  always @* begin", "    case (slot)"]
    for n, s in enumerate(slots):
        val = "".join(f"{v:016x}" for v in reversed(s))
        out.append(f"      5'd{n}: rc = 768'h{val};")
    out += ["      default: rc = 768'h0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(out)


def _balanced_xor(terms):
    if not terms:
        return "1'b0"
    cur = list(terms)
    while len(cur) > 1:
        nxt = []
        for i in range(0, len(cur), 2):
            if i + 1 < len(cur):
                nxt.append(f"({cur[i]} ^ {cur[i + 1]})")
            else:
                nxt.append(cur[i])
        cur = nxt
    return cur[0]


def gen_tower_maps():
    t7, poly = ref.tower_basis()
    out = []
    for name, cols in (("qsag_tower128_to_poly", t7), ("qsag_poly_to_tower128", poly)):
        out += [f"module {name} (", "  input  wire [127:0] x,", "  output wire [127:0] y", ");"]
        for r in range(128):
            terms = [f"x[{c}]" for c in range(128) if ((cols[c] >> r) & 1)]
            out.append(f"  assign y[{r}] = {_balanced_xor(terms)};")
        out += ["endmodule", ""]
    return "\n".join(out)


