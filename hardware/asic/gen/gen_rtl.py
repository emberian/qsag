#!/usr/bin/env python3
"""Emit the generated QSAG-NI RTL (carry-save Goldilocks datapaths, Poseidon2 linear
layers and round constants, Ext4 coefficient accumulators, GF(2^128) tower maps).

  python3 gen/gen_rtl.py rtl/
"""
import sys
import os

sys.path.insert(0, os.path.dirname(__file__))
from csagen import Mod, Csa, final, P
import qsag_ref as ref

HDR = "// GENERATED by hardware/asic/gen/gen_rtl.py. Do not edit; regenerate.\n"
MULQ = 3  # quotient bound of the multiplier fold (4 parallel final candidates)
stats = {}


def gen_mul_tree():
    m = Mod("qsag_gl64_mul_tree", ["input  wire [63:0] a", "input  wire [63:0] b",
                                   "output wire [127:0] s", "output wire [127:0] c"])
    csa = Csa(m)
    for i in range(64):
        for j in range(64):
            csa.raw(m.w(f"a[{i}] & b[{j}]"), i + j)
    csa.compress()
    # s + c = a*b < 2^128 as integers and every bit is non-negative, so a bit of weight
    # >= 2^128 is constant 0; such carries are not emitted.
    xs = [csa.cols[w][0] if len(csa.cols.get(w, [])) > 0 else "1'b0" for w in range(128)]
    ys = [csa.cols[w][1] if len(csa.cols.get(w, [])) > 1 else "1'b0" for w in range(128)]
    m.raw(f"assign s = {{{', '.join(reversed(xs))}}};")
    m.raw(f"assign c = {{{', '.join(reversed(ys))}}};")
    stats["mul_tree_fa"] = csa.fas
    return m.text()


def gen_fold():
    """(s, c) with s + c = product -> two rows x, y with x + y = product (mod p), x + y < 4p."""
    m = Mod("qsag_gl64_fold", ["input  wire [127:0] s", "input  wire [127:0] c",
                               "output wire [FW-1:0] x", "output wire [FW-1:0] y"])
    csa = Csa(m)
    csa.term("s", 128)
    csa.term("c", 128)
    x, y, w, q = csa.rows("r", MULQ)
    m.raw(f"assign x = {x};")
    m.raw(f"assign y = {y};")
    m.ports[2] = f"output wire [{w - 1}:0] x"
    m.ports[3] = f"output wire [{w - 1}:0] y"
    stats["fold"] = (w, q, csa.fas)
    return m.text(), w, q


def gen_mul(fw, fq):
    return f"""// (a * b) mod p, canonical, for any 64-bit a, b: partial-product tree, reduction folded
// into the carry-save rows, one level of parallel compound adders.
module qsag_gl64_mul_csa (
  input  wire [63:0] a,
  input  wire [63:0] b,
  output wire [63:0] r
);
  wire [127:0] s, c;
  wire [{fw - 1}:0] x, y;
  qsag_gl64_mul_tree u_tree (.a(a), .b(b), .s(s), .c(c));
  qsag_gl64_fold u_fold (.s(s), .c(c), .x(x), .y(y));
  qsag_gl64_final_par #(.W({fw}), .NJ({fq + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""


def gen_reduce128():
    m = Mod("qsag_gl64_reduce128_csa", ["input  wire [127:0] v", "output wire [63:0] r"])
    csa = Csa(m)
    csa.term("v", 128)
    x, y, w, q = csa.rows("r", None)
    final(m, "u_final", x, y, w, q, "r", True)
    stats["reduce128"] = (w, q, csa.fas)
    return m.text()


def gen_ext4_coef(k):
    ports = []
    for i in range(4):
        ports += [f"input  wire [127:0] s{i}", f"input  wire [127:0] c{i}"]
    m = Mod(f"qsag_ext4_coef{k}", ports + ["input  wire [63:0] z", "output wire [63:0] r"])
    csa = Csa(m)
    for i in range(4):
        for sig in (f"s{i}", f"c{i}"):
            if i <= k:
                csa.term(sig, 128)
            else:  # weight 7 = 8 - 1
                csa.term(sig, 128, 3)
                csa.term(sig, 128, 0, -1)
    csa.term("z", 64)
    x, y, w, q = csa.rows("r", MULQ)
    final(m, "u_final", x, y, w, q, "r", True)
    stats[f"ext4_coef{k}"] = (w, q, csa.fas)
    return m.text()


def weighted_exact(csa, sig, width, weight):
    """weight * sig as unfolded integer bits (no modular folding, no constant)."""
    b = 0
    while weight >> b:
        if (weight >> b) & 1:
            for i in range(width):
                csa.raw(f"{sig}[{i}]", b + i)
        b += 1


def gen_me():
    """M_E(x) + rc. lane(b, i) = 3i + b; y(b,i) = 2x(b,i) + 3x(b,i+1) + x(b,i+2) + x(b,i+3);
    out(b,i) = y(b,i) + sum_b' y(b',i)."""
    m = Mod("qsag_p2_me", ["input  wire [767:0] x", "input  wire [767:0] rc", "output wire [767:0] y"])
    lane = lambda b, i: 3 * (i % 4) + b
    for l in range(12):
        m.raw(f"wire [63:0] x{l} = x[{64 * l + 63}:{64 * l}];")
        m.raw(f"wire [63:0] rc{l} = rc[{64 * l + 63}:{64 * l}];")
    yrows = {}
    fas = 0
    for b in range(3):
        for i in range(4):
            csa = Csa(m)
            for off, wt in enumerate([2, 3, 1, 1]):
                weighted_exact(csa, f"x{lane(b, i + off)}", 64, wt)
            # exact integer rows: 7 * (2^64 - 1) < 2^67
            csa.compress()
            width = csa.bound.bit_length()
            xs = [csa.cols[w][0] if len(csa.cols.get(w, [])) > 0 else "1'b0" for w in range(width)]
            ys = [csa.cols[w][1] if len(csa.cols.get(w, [])) > 1 else "1'b0" for w in range(width)]
            m.raw(f"wire [{width - 1}:0] m4x_{b}_{i} = {{{', '.join(reversed(xs))}}};")
            m.raw(f"wire [{width - 1}:0] m4y_{b}_{i} = {{{', '.join(reversed(ys))}}};")
            yrows[(b, i)] = width
            fas += csa.fas
    for b in range(3):
        for i in range(4):
            csa = Csa(m)
            for bb in range(3):
                for r in ("x", "y"):
                    csa.term(f"m4{r}_{bb}_{i}", yrows[(bb, i)], 1 if bb == b else 0)
            csa.term(f"rc{lane(b, i)}", 64)
            x, y, w, q = csa.rows(f"o{b}_{i}_", None)
            final(m, f"u_f{b}_{i}", x, y, w, q, f"y[{64 * lane(b, i) + 63}:{64 * lane(b, i)}]", False)
            fas += csa.fas
    stats["me_fa"] = fas
    return m.text()


def gen_mi(fused, fw):
    """M_I(s0, x1..x11) + rc. Plain: s0 = x0 canonical. Fused: s0 = sx + sy (carry-save rows
    of the lane-0 S-box product, before its final adder)."""
    name = "qsag_p2_mi_fused" if fused else "qsag_p2_mi"
    ports = (["input  wire [%d:0] sx" % (fw - 1), "input  wire [%d:0] sy" % (fw - 1)] if fused else [])
    m = Mod(name, ports + ["input  wire [767:0] x", "input  wire [767:0] rc", "output wire [767:0] y"])
    for l in range(12):
        m.raw(f"wire [63:0] x{l} = x[{64 * l + 63}:{64 * l}];")
        m.raw(f"wire [63:0] rc{l} = rc[{64 * l + 63}:{64 * l}];")
    # shared: U + V = x1 + ... + x11 (exact integer)
    csa = Csa(m)
    for l in range(1, 12):
        for bpos in range(64):
            csa.raw(f"x{l}[{bpos}]", bpos)
    csa.compress()
    uw = csa.bound.bit_length()
    xs = [csa.cols[w][0] if len(csa.cols.get(w, [])) > 0 else "1'b0" for w in range(uw)]
    ys = [csa.cols[w][1] if len(csa.cols.get(w, [])) > 1 else "1'b0" for w in range(uw)]
    m.raw(f"wire [{uw - 1}:0] su = {{{', '.join(reversed(xs))}}};")
    m.raw(f"wire [{uw - 1}:0] sv = {{{', '.join(reversed(ys))}}};")
    fas = csa.fas
    s0 = [("sx", fw), ("sy", fw)] if fused else [("x0", 64)]
    for l in range(12):
        csa = Csa(m)
        csa.term("su", uw)
        csa.term("sv", uw)
        csa.term(f"rc{l}", 64)
        if l > 0:
            csa.term(f"x{l}", 64, l - 1)  # diag 2^(l-1)
        csa.compress()  # early-arriving register terms first
        for sig, w in s0:
            if l == 0:  # (1 - 64) * s0
                csa.term(sig, w)
                csa.term(sig, w, 6, -1)
            else:
                csa.term(sig, w)
        x, y, w, q = csa.rows(f"o{l}_", None)
        final(m, f"u_f{l}", x, y, w, q, f"y[{64 * l + 63}:{64 * l}]", False)
        fas += csa.fas
    stats[name + "_fa"] = fas
    return m.text()


def gen_canopy_ff():
    """ff_i = l_i + 2 r_i + 4 c_i (mod p), i < 4; l = st[0..3], r = st[4..7], c = st[8..11]."""
    m = Mod("qsag_p2_canopy_ff", ["input  wire [767:0] x", "output wire [255:0] ff"])
    for l in range(12):
        m.raw(f"wire [63:0] x{l} = x[{64 * l + 63}:{64 * l}];")
    for i in range(4):
        csa = Csa(m)
        csa.term(f"x{i}", 64)
        csa.term(f"x{4 + i}", 64, 1)
        csa.term(f"x{8 + i}", 64, 2)
        x, y, w, q = csa.rows(f"o{i}_", None)
        final(m, f"u_f{i}", x, y, w, q, f"ff[{64 * i + 63}:{64 * i}]", False)
    return m.text()


def gen_rc():
    """slot n = constants added by the linear layer that precedes S-box layer n (slot 30: none)."""
    slots = []
    for r in range(4):
        slots.append([ref.p2_rc(0, r, l) for l in range(12)])
    for r in range(22):
        slots.append([ref.p2_rc(1, r, 0)] + [0] * 11)
    for r in range(4):
        slots.append([ref.p2_rc(2, r, l) for l in range(12)])
    slots.append([0] * 12)
    out = ["module qsag_p2_rc (", "  input  wire [4:0] slot,", "  output reg  [767:0] rc", ");",
           "  always @* begin", "    case (slot)"]
    for n, s in enumerate(slots):
        val = "".join(f"{v:016x}" for v in reversed(s))
        out.append(f"      5'd{n}: rc = 768'h{val};")
    out += ["      default: rc = 768'h0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(out)


def gen_tower_maps():
    t7, poly = ref.tower_basis()
    out = []
    for name, cols in (("qsag_tower128_to_poly", t7), ("qsag_poly_to_tower128", poly)):
        out += [f"module {name} (", "  input  wire [127:0] x,", "  output wire [127:0] y", ");"]
        for r in range(128):
            mask = sum(((cols[c] >> r) & 1) << c for c in range(128))
            out.append(f"  assign y[{r}] = ^(x & 128'h{mask:032x});")
        out += ["endmodule", ""]
    return "\n".join(out)


def main(outdir):
    fold_txt, fw, fq = gen_fold()
    gl = HDR + gen_mul_tree() + "\n" + fold_txt + "\n" + gen_mul(fw, fq) + "\n" + gen_reduce128()
    open(os.path.join(outdir, "qsag_asic_gl64_csa_gen.sv"), "w").write(gl)
    p2 = HDR + "\n".join(gen_ext4_coef(k) for k in range(4)) + "\n" + gen_me() + "\n" + gen_mi(False, fw) + "\n" + \
        gen_mi(True, fw) + "\n" + gen_canopy_ff() + "\n" + gen_rc()
    open(os.path.join(outdir, "qsag_asic_ext4_p2_gen.sv"), "w").write(p2)
    open(os.path.join(outdir, "qsag_asic_tower_maps_gen.sv"), "w").write(HDR + gen_tower_maps())
    open(os.path.join(outdir, "qsag_asic_gen_params.svh"), "w").write(
        HDR + f"`define QSAG_FOLD_W {fw}\n`define QSAG_FOLD_NJ {fq + 1}\n")
    for k, v in stats.items():
        print(k, v)


if __name__ == "__main__":
    main(sys.argv[1])
