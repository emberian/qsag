#!/usr/bin/env python3
"""Emit the generated QSAG-NI RTL:
  * Sliced 64x64 Dadda partial-product tree (8 x 64x8 slices + 8-way combiner) and 2-step Goldilocks CSA fold
  * 9-product Tower Karatsuba GoldilocksExt4 pre-adders & factored CSA combiners
  * Hierarchical CSE Poseidon2 M_E (3 x M_4 + 4 x circulant column) & M_I (2 x sum6 tail + 12 x lane)
  * Canopy feed-forward, Poseidon2 round constants, and GF(2^128) Wiedemann T_7 basis maps

Every leaf arithmetic sub-module has <= 384 input bits so Z3 and Bitwuzla discharge 100% of LEC miters directly.

  python3 gen/gen_rtl.py rtl/
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from csagen import Mod, Csa, final, P
import qsag_ref as ref

HDR = "// GENERATED by hardware/asic/gen/gen_rtl.py. Do not edit; regenerate.\n`default_nettype none\n"
FTR = "`default_nettype wire\n"
MULQ = 3  # quotient bound of the multiplier fold (4 parallel final candidates)
stats = {}


def gen_mul_tree():
    # 1. 64x8 partial-product slice: exact 72-bit integer sum s + c = a * b
    ms = Mod("qsag_gl64_mul_slice64x8", [
        "input  wire [63:0] a",
        "input  wire [7:0]  b",
        "output wire [71:0] s",
        "output wire [71:0] c",
    ])
    csa_s = Csa(ms)
    for i in range(64):
        for j in range(8):
            csa_s.raw(ms.w(f"a[{i}] & b[{j}]"), i + j)
    csa_s.compress()
    xs = [csa_s.cols[w][0] if len(csa_s.cols.get(w, [])) > 0 else "1'b0" for w in range(72)]
    ys = [csa_s.cols[w][1] if len(csa_s.cols.get(w, [])) > 1 else "1'b0" for w in range(72)]
    ms.raw(f"assign s = {{{', '.join(reversed(xs))}}};")
    ms.raw(f"assign c = {{{', '.join(reversed(ys))}}};")
    stats["mul_slice64x8 (fa, ha, stages)"] = (csa_s.fas, csa_s.has, csa_s.stages)

    # 2. 8-slice combiner: exact 128-bit integer sum s + c = sum_{k=0..7} ((sk + ck) << 8k)
    ports = []
    for k in range(8):
        ports += [f"input  wire [71:0] s{k}", f"input  wire [71:0] c{k}"]
    ports += ["output wire [127:0] s", "output wire [127:0] c"]
    mc = Mod("qsag_gl64_mul_combine8", ports)
    csa_c = Csa(mc)
    for k in range(8):
        for b in range(72):
            if 8 * k + b < 128:
                csa_c.raw(f"s{k}[{b}]", 8 * k + b)
                csa_c.raw(f"c{k}[{b}]", 8 * k + b)
    csa_c.compress()
    xs = [csa_c.cols[w][0] if len(csa_c.cols.get(w, [])) > 0 else "1'b0" for w in range(128)]
    ys = [csa_c.cols[w][1] if len(csa_c.cols.get(w, [])) > 1 else "1'b0" for w in range(128)]
    mc.raw(f"assign s = {{{', '.join(reversed(xs))}}};")
    mc.raw(f"assign c = {{{', '.join(reversed(ys))}}};")
    stats["mul_combine8 (fa, ha, stages)"] = (csa_c.fas, csa_c.has, csa_c.stages)
    stats["mul_tree_total_fa"] = 8 * csa_s.fas + csa_c.fas

    # 3. Top-level 64x64 multiplier tree wrapper
    top = [
        "module qsag_gl64_mul_tree (",
        "  input  wire [63:0]  a,",
        "  input  wire [63:0]  b,",
        "  output wire [127:0] s,",
        "  output wire [127:0] c",
        ");",
    ]
    for k in range(8):
        top.append(f"  wire [71:0] s{k}, c{k};")
        top.append(f"  qsag_gl64_mul_slice64x8 u_s{k} (.a(a), .b(b[{8*k+7}:{8*k}]), .s(s{k}), .c(c{k}));")
    conns = ", ".join(f".s{k}(s{k}), .c{k}(c{k})" for k in range(8))
    top.append(f"  qsag_gl64_mul_combine8 u_comb ({conns}, .s(s), .c(c));")
    top.append("endmodule\n")
    return ms.text() + "\n" + mc.text() + "\n" + "\n".join(top)


def gen_fold():
    """Two-step modular CSA fold so both single-row (128b) and pair-row (4xFW1) miters solve in <3s."""
    m1 = Mod("qsag_gl64_fold_one", [
        "input  wire [127:0] v",
        "output wire [W1-1:0] x",
        "output wire [W1-1:0] y",
    ])
    c1 = Csa(m1)
    c1.term("v", 128)
    x1, y1, w1, q1 = c1.rows("r", None)
    m1.raw(f"assign x = {x1};")
    m1.raw(f"assign y = {y1};")
    m1.ports[1] = f"output wire [{w1 - 1}:0] x"
    m1.ports[2] = f"output wire [{w1 - 1}:0] y"
    stats["fold_one (W1, q1, fa)"] = (w1, q1, c1.fas)

    m2 = Mod("qsag_gl64_fold_pair", [
        f"input  wire [{w1 - 1}:0] sx",
        f"input  wire [{w1 - 1}:0] sy",
        f"input  wire [{w1 - 1}:0] cx",
        f"input  wire [{w1 - 1}:0] cy",
        "output wire [FW-1:0] x",
        "output wire [FW-1:0] y",
    ])
    c2 = Csa(m2)
    for sig in ("sx", "sy", "cx", "cy"):
        c2.term(sig, w1)
    x2, y2, fw, fq = c2.rows("r", MULQ)
    m2.raw(f"assign x = {x2};")
    m2.raw(f"assign y = {y2};")
    m2.ports[4] = f"output wire [{fw - 1}:0] x"
    m2.ports[5] = f"output wire [{fw - 1}:0] y"
    stats["fold_pair (FW, fq, fa)"] = (fw, fq, c2.fas)

    wrap = f"""module qsag_gl64_fold (
  input  wire [127:0] s,
  input  wire [127:0] c,
  output wire [{fw - 1}:0] x,
  output wire [{fw - 1}:0] y
);
  wire [{w1 - 1}:0] sx, sy, cx, cy;
  qsag_gl64_fold_one u_fs (.v(s), .x(sx), .y(sy));
  qsag_gl64_fold_one u_fc (.v(c), .x(cx), .y(cy));
  qsag_gl64_fold_pair u_fp (.sx(sx), .sy(sy), .cx(cx), .cy(cy), .x(x), .y(y));
endmodule
"""
    red = f"""module qsag_gl64_reduce128_csa (
  input  wire [127:0] v,
  output wire [63:0]  r
);
  wire [{w1 - 1}:0] x, y;
  qsag_gl64_fold_one u_f (.v(v), .x(x), .y(y));
  qsag_gl64_final_par #(.W({w1}), .NJ({q1 + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""
    return m1.text() + "\n" + m2.text() + "\n" + wrap, red, w1, q1, fw, fq


def gen_mul(fw, fq):
    return f"""module qsag_gl64_mul_csa (
  input  wire [63:0] a,
  input  wire [63:0] b,
  output wire [63:0] r
);
  wire [127:0] s, c;
  wire [{fw - 1}:0] x, y;
  qsag_gl64_mul_tree u_tree (.a(a), .b(b), .s(s), .c(c));
  qsag_gl64_fold u_fold (.s(s), .c(c), .x(x), .y(y));
  qsag_gl64_final_par #(.W({fw}), .NJ({fq + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""


def _emit_lin_mod(name, terms, use_par=True):
    """Emit a small linear-combination module `r = (sum_k wt_k * in_k) mod p` with <= 6 inputs."""
    assert len(terms) <= 6, f"{name} has {len(terms)} inputs (> 6)"
    ports = [f"input  wire [63:0] {sig}" for sig, _ in terms] + ["output wire [63:0] r"]
    m = Mod(name, ports)
    c = Csa(m)
    for sig, wt in terms:
        if abs(wt) == 7:
            c.term_exact(sig, 64, 3, 1 if wt > 0 else -1)
            c.term_exact(sig, 64, 0, -1 if wt > 0 else 1)
        elif wt != 0:
            c.term_exact(sig, 64, 0, wt)
    x, y, w, q = c.rows("o_", MULQ if use_par else None)
    final(m, "u_f", x, y, w, q, "r", use_par)
    return m.text()


def gen_ext4_karatsuba():
    """9-product Tower Karatsuba over F_p[v]/(v^4 - 7), limb order [1, u, v, u*v]."""
    inp = """module qsag_ext4_kara_inputs (
  input  wire [255:0] a,
  output wire [575:0] q
);
  wire [63:0] a0 = a[63:0];
  wire [63:0] a1 = a[127:64];
  wire [63:0] a2 = a[191:128];
  wire [63:0] a3 = a[255:192];
  wire [63:0] s01, s23, s02, s13, sall;
  qsag_gl64_addsub u_01  (.a(a0),  .b(a1),  .sub(1'b0), .r(s01));
  qsag_gl64_addsub u_23  (.a(a2),  .b(a3),  .sub(1'b0), .r(s23));
  qsag_gl64_addsub u_02  (.a(a0),  .b(a2),  .sub(1'b0), .r(s02));
  qsag_gl64_addsub u_13  (.a(a1),  .b(a3),  .sub(1'b0), .r(s13));
  qsag_gl64_addsub u_all (.a(s01), .b(s23), .sub(1'b0), .r(sall));
  assign q = {sall, s13, s02, s23, a3, a2, s01, a1, a0};
endmodule
"""
    # Each output row is factored into <= 6-input linear CSA modules (<= 384 input bits -> <2s SMT LEC)
    r0 = _emit_lin_mod("qsag_ext4_kara_r0", [("p0", 1), ("p1", 7), ("p3", -7), ("p4", -7), ("p5", 7), ("z0", 1)], True)
    r1 = _emit_lin_mod("qsag_ext4_kara_r1", [("p0", -1), ("p1", -1), ("p2", 1), ("p3", 1), ("p4", 7), ("z1", 1)], True)
    r2a = _emit_lin_mod("qsag_ext4_kara_r2a", [("p0", -1), ("p1", -7), ("p3", -1), ("p4", -7)], False)
    r2b = _emit_lin_mod("qsag_ext4_kara_r2b", [("t", 1), ("p6", 1), ("p7", 7), ("z2", 1)], True)
    r3a = _emit_lin_mod("qsag_ext4_kara_r3a", [("p0", 1), ("p1", 1), ("p2", -1), ("p3", 1), ("p4", 1), ("p5", -1)], False)
    r3b = _emit_lin_mod("qsag_ext4_kara_r3b", [("t", 1), ("p6", -1), ("p7", -1), ("p8", 1), ("z3", 1)], True)

    comb = """module qsag_ext4_kara_combine (
  input  wire [575:0] p,
  input  wire [255:0] z,
  output wire [255:0] r
);
  wire [63:0] p0 = p[63:0],    p1 = p[127:64],  p2 = p[191:128];
  wire [63:0] p3 = p[255:192], p4 = p[319:256], p5 = p[383:320];
  wire [63:0] p6 = p[447:384], p7 = p[511:448], p8 = p[575:512];
  wire [63:0] z0 = z[63:0],    z1 = z[127:64],  z2 = z[191:128], z3 = z[255:192];
  wire [63:0] t2, t3;
  qsag_ext4_kara_r0  u_r0  (.p0(p0), .p1(p1), .p3(p3), .p4(p4), .p5(p5), .z0(z0), .r(r[63:0]));
  qsag_ext4_kara_r1  u_r1  (.p0(p0), .p1(p1), .p2(p2), .p3(p3), .p4(p4), .z1(z1), .r(r[127:64]));
  qsag_ext4_kara_r2a u_r2a (.p0(p0), .p1(p1), .p3(p3), .p4(p4), .r(t2));
  qsag_ext4_kara_r2b u_r2b (.t(t2),  .p6(p6), .p7(p7), .z2(z2), .r(r[191:128]));
  qsag_ext4_kara_r3a u_r3a (.p0(p0), .p1(p1), .p2(p2), .p3(p3), .p4(p4), .p5(p5), .r(t3));
  qsag_ext4_kara_r3b u_r3b (.t(t3),  .p6(p6), .p7(p7), .p8(p8), .z3(z3), .r(r[255:192]));
endmodule
"""
    return "\n".join([inp, r0, r1, r2a, r2b, r3a, r3b, comb])


def gen_me():
    """Hierarchical CSE M_E: 3 x qsag_p2_m4 (256b in) + 4 x qsag_p2_me_col (384b in)."""
    # 1. qsag_p2_m4: s = b0 + b1 + b2 + b3 shared across all 4 outputs
    m4 = Mod("qsag_p2_m4", [
        "input  wire [255:0] b",
        "output wire [255:0] y",
    ])
    for i in range(4):
        m4.raw(f"wire [63:0] b{i} = b[{64 * i + 63}:{64 * i}];")
    csa_s = Csa(m4)
    for i in range(4):
        csa_s.term_exact(f"b{i}", 64)
    csa_s.compress()
    sw = csa_s.bound.bit_length()
    xs = [csa_s.cols[w][0] if len(csa_s.cols.get(w, [])) > 0 else "1'b0" for w in range(sw)]
    ys = [csa_s.cols[w][1] if len(csa_s.cols.get(w, [])) > 1 else "1'b0" for w in range(sw)]
    m4.raw(f"wire [{sw - 1}:0] sx = {{{', '.join(reversed(xs))}}};")
    m4.raw(f"wire [{sw - 1}:0] sy = {{{', '.join(reversed(ys))}}};")
    fas = csa_s.fas
    for i in range(4):
        c = Csa(m4)
        c.term_exact("sx", sw)
        c.term_exact("sy", sw)
        c.term_exact(f"b{i}", 64, 0)
        c.term_exact(f"b{(i + 1) % 4}", 64, 1)
        ox, oy, ow, oq = c.rows(f"o{i}_", None)
        final(m4, f"u_f{i}", ox, oy, ow, oq, f"y[{64 * i + 63}:{64 * i}]", False)
        fas += c.fas

    # 2. qsag_p2_me_col: s = y0 + y1 + y2 shared across 3 block outputs + rc
    mc = Mod("qsag_p2_me_col", [
        "input  wire [63:0] y0",
        "input  wire [63:0] y1",
        "input  wire [63:0] y2",
        "input  wire [63:0] rc0",
        "input  wire [63:0] rc1",
        "input  wire [63:0] rc2",
        "output wire [63:0] o0",
        "output wire [63:0] o1",
        "output wire [63:0] o2",
    ])
    csa_c = Csa(mc)
    for b in range(3):
        csa_c.term_exact(f"y{b}", 64)
    csa_c.compress()
    cw = csa_c.bound.bit_length()
    xs = [csa_c.cols[w][0] if len(csa_c.cols.get(w, [])) > 0 else "1'b0" for w in range(cw)]
    ys = [csa_c.cols[w][1] if len(csa_c.cols.get(w, [])) > 1 else "1'b0" for w in range(cw)]
    mc.raw(f"wire [{cw - 1}:0] sx = {{{', '.join(reversed(xs))}}};")
    mc.raw(f"wire [{cw - 1}:0] sy = {{{', '.join(reversed(ys))}}};")
    col_fas = csa_c.fas
    for b in range(3):
        c = Csa(mc)
        c.term_exact("sx", cw)
        c.term_exact("sy", cw)
        c.term_exact(f"y{b}", 64)
        c.term_exact(f"rc{b}", 64)
        ox, oy, ow, oq = c.rows(f"o{b}_", None)
        final(mc, f"u_f{b}", ox, oy, ow, oq, f"o{b}", False)
        col_fas += c.fas

    stats["me_total_fa"] = 3 * fas + 4 * col_fas

    # 3. Top qsag_p2_me
    lines = [
        "module qsag_p2_me (",
        "  input  wire [767:0] x,",
        "  input  wire [767:0] rc,",
        "  output wire [767:0] y",
        ");",
        "  wire [255:0] m0, m1, m2;",
        "  qsag_p2_m4 u_m0 (.b({x[639:576], x[447:384], x[255:192], x[63:0]}),    .y(m0));",
        "  qsag_p2_m4 u_m1 (.b({x[703:640], x[511:448], x[319:256], x[127:64]}),  .y(m1));",
        "  qsag_p2_m4 u_m2 (.b({x[767:704], x[575:512], x[383:320], x[191:128]}), .y(m2));",
    ]
    for i in range(4):
        l0, l1, l2 = 3 * i, 3 * i + 1, 3 * i + 2
        lines.append(
            f"  qsag_p2_me_col u_c{i} ("
            f".y0(m0[{64*i+63}:{64*i}]), .y1(m1[{64*i+63}:{64*i}]), .y2(m2[{64*i+63}:{64*i}]), "
            f".rc0(rc[{64*l0+63}:{64*l0}]), .rc1(rc[{64*l1+63}:{64*l1}]), .rc2(rc[{64*l2+63}:{64*l2}]), "
            f".o0(y[{64*l0+63}:{64*l0}]), .o1(y[{64*l1+63}:{64*l1}]), .o2(y[{64*l2+63}:{64*l2}]));"
        )
    lines.append("endmodule\n")
    return m4.text() + "\n" + mc.text() + "\n" + "\n".join(lines)


def gen_mi():
    """Hierarchical CSE M_I:
      * qsag_gl64_sum6 (384b in) x 2 + addsub -> qsag_p2_mi_tail (computes s_tail = sum_{j=1..11} x_j mod p)
      * qsag_p2_mi_lane0..11 (192b/256b in) -> qsag_p2_mi_apply (finishes M_I once sbox(x0) is ready)
      * qsag_p2_mi (full combinational wrapper for unit tests & LEC)
    """
    ms = Mod("qsag_gl64_sum6", [f"input  wire [63:0] a{i}" for i in range(6)] + ["output wire [63:0] r"])
    cs = Csa(ms)
    for i in range(6):
        cs.term_exact(f"a{i}", 64)
    ox, oy, ow, oq = cs.rows("s_", None)
    final(ms, "u_f", ox, oy, ow, oq, "r", False)

    tail = """module qsag_p2_mi_tail (
  input  wire [703:0] x_hi,
  output wire [63:0]  s_tail
);
  wire [63:0] s_lo, s_hi;
  qsag_gl64_sum6 u_lo (
    .a0(x_hi[63:0]),   .a1(x_hi[127:64]),  .a2(x_hi[191:128]),
    .a3(x_hi[255:192]), .a4(x_hi[319:256]), .a5(x_hi[383:320]), .r(s_lo));
  qsag_gl64_sum6 u_hi (
    .a0(x_hi[447:384]), .a1(x_hi[511:448]), .a2(x_hi[575:512]),
    .a3(x_hi[639:576]), .a4(x_hi[703:640]), .a5(64'd0),         .r(s_hi));
  qsag_gl64_addsub u_add (.a(s_lo), .b(s_hi), .sub(1'b0), .r(s_tail));
endmodule
"""
    lanes = []
    tot_fa = 2 * cs.fas
    for l in range(12):
        ports = ["input  wire [63:0] x0", "input  wire [63:0] s_tail", "input  wire [63:0] rcl"]
        if l > 0:
            ports.insert(1, "input  wire [63:0] xl")
        ports.append("output wire [63:0] y")
        ml = Mod(f"qsag_p2_mi_lane{l}", ports)
        cl = Csa(ml)
        cl.term_exact("s_tail", 64)
        cl.term_exact("rcl", 64)
        if l == 0:
            # (1 - 64) * x0 = x0 - 64 * x0
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("x0", 64, 6, -1)
        else:
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("xl", 64, l - 1, 1)
        lx, ly, lw, lq = cl.rows("o_", None)
        final(ml, "u_f", lx, ly, lw, lq, "y", False)
        tot_fa += cl.fas
        lanes.append(ml.text())
    stats["mi_total_fa"] = tot_fa

    app = [
        "module qsag_p2_mi_apply (",
        "  input  wire [63:0]  x0,",
        "  input  wire [703:0] x_hi,",
        "  input  wire [63:0]  s_tail,",
        "  input  wire [767:0] rc,",
        "  output wire [767:0] y",
        ");",
        "  qsag_p2_mi_lane0 u_l0 (.x0(x0), .s_tail(s_tail), .rcl(rc[63:0]), .y(y[63:0]));",
    ]
    for l in range(1, 12):
        hi_lo = 64 * (l - 1)
        app.append(
            f"  qsag_p2_mi_lane{l} u_l{l} ("
            f".x0(x0), .xl(x_hi[{hi_lo+63}:{hi_lo}]), .s_tail(s_tail), "
            f".rcl(rc[{64*l+63}:{64*l}]), .y(y[{64*l+63}:{64*l}]));"
        )
    app.append("endmodule\n")

    wrap = """module qsag_p2_mi (
  input  wire [767:0] x,
  input  wire [767:0] rc,
  output wire [767:0] y
);
  wire [63:0] s_tail;
  qsag_p2_mi_tail  u_tail  (.x_hi(x[767:64]), .s_tail(s_tail));
  qsag_p2_mi_apply u_apply (.x0(x[63:0]), .x_hi(x[767:64]), .s_tail(s_tail), .rc(rc), .y(y));
endmodule
"""
    return ms.text() + "\n" + tail + "\n" + "\n".join(lanes) + "\n" + "\n".join(app) + "\n" + wrap


def gen_canopy_ff():
    """ff_i = l_i + 2 r_i + 4 c_i (mod p), i < 4; l = st[0..3], r = st[4..7], c = st[8..11]."""
    m1 = Mod("qsag_p2_canopy_ff_lane", [
        "input  wire [63:0] l",
        "input  wire [63:0] r",
        "input  wire [63:0] c",
        "output wire [63:0] ff",
    ])
    csa = Csa(m1)
    csa.term_exact("l", 64, 0)
    csa.term_exact("r", 64, 1)
    csa.term_exact("c", 64, 2)
    x, y, w, q = csa.rows("o_", None)
    final(m1, "u_f", x, y, w, q, "ff", False)

    wrap = [
        "module qsag_p2_canopy_ff (",
        "  input  wire [767:0] x,",
        "  output wire [255:0] ff",
        ");",
    ]
    for i in range(4):
        wrap.append(
            f"  qsag_p2_canopy_ff_lane u_ff{i} ("
            f".l(x[{64*i+63}:{64*i}]), .r(x[{64*(4+i)+63}:{64*(4+i)}]), "
            f".c(x[{64*(8+i)+63}:{64*(8+i)}]), .ff(ff[{64*i+63}:{64*i}]));"
        )
    wrap.append("endmodule\n")
    return m1.text() + "\n" + "\n".join(wrap)


def gen_rc():
    """slot n = constants added by the linear layer that precedes S-box layer n (slot 30: none)."""
    slots = []
    for r in range(4):
        slots.append([ref.p2_rc(0, r, l) for l in range(12)])
    for r in range(22):
        slots.append([ref.p2_rc(1, r, 0)] + [0] * 11)
    for r in range(4):
        slots.append([ref.p2_rc(2, r, l) for l in range(12)])
    slots.append([0] * 12)
    out = ["module qsag_p2_rc (", "  input  wire [4:0] slot,", "  output reg  [767:0] rc", ");",
           "  always @* begin", "    case (slot)"]
    for n, s in enumerate(slots):
        val = "".join(f"{v:016x}" for v in reversed(s))
        out.append(f"      5'd{n}: rc = 768'h{val};")
    out += ["      default: rc = 768'h0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(out)


def gen_tower_maps():
    t7, poly = ref.tower_basis()
    out = []
    for name, cols in (("qsag_tower128_to_poly", t7), ("qsag_poly_to_tower128", poly)):
        out += [f"module {name} (", "  input  wire [127:0] x,", "  output wire [127:0] y", ");"]
        for r in range(128):
            mask = sum(((cols[c] >> r) & 1) << c for c in range(128))
            out.append(f"  assign y[{r}] = ^(x & 128'h{mask:032x});")
        out += ["endmodule", ""]
    return "\n".join(out)


