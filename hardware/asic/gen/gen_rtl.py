#!/usr/bin/env python3
"""Emit the generated QSAG-NI RTL:
  * Balanced 4-row-per-stage 64x64 Dadda partial-product tree (16 x 64x4 slices + 4-level binary
    combiner tree) and 2-step Goldilocks CSA fold (`fold_one` + `fold_pair`)
  * True 2-level Tower Karatsuba `GoldilocksExt4` (`3 x F_{p^2}` Karatsuba + outer `Ext4` combiner,
    every leaf <= 4 CSA rows)
  * Hierarchical CSE Poseidon2 `M_E` (`csa4 + 4 x m4_lane`, `csa3 + 3 x me_col_lane`) & `M_I`
    (`2 x csa3 + sum4_csa` tail + `12 x mi_lane0..11`)
  * Canopy feed-forward, Poseidon2 round constants, and balanced-XOR-tree GF(2^128) Wiedemann `T_7` maps

Every leaf arithmetic sub-module compresses <= 4 rows (`<= 272` input bits) so Z3 and Bitwuzla
discharge 100% of compositional LEC miters in < 15s (`0` undecided miters).

  python3 gen/gen_rtl.py rtl/
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from csagen import Mod, Csa, final, P
import qsag_ref as ref

HDR = "// GENERATED by hardware/asic/gen/gen_rtl.py. Do not edit; regenerate.\n`default_nettype none\n"
FTR = "`default_nettype wire\n"
stats = {}


def _assign_rows(mod, csa, w_out, s_name="s", c_name="c"):
    csa.compress()
    xs = [csa.cols[w][0] if len(csa.cols.get(w, [])) > 0 else "1'b0" for w in range(w_out)]
    ys = [csa.cols[w][1] if len(csa.cols.get(w, [])) > 1 else "1'b0" for w in range(w_out)]
    mod.raw(f"assign {s_name} = {{{', '.join(reversed(xs))}}};")
    mod.raw(f"assign {c_name} = {{{', '.join(reversed(ys))}}};")


def gen_mul_tree():
    """64x64 Dadda tree factored into <=4-row stages for <4s symbolic bit-vector LEC:
      * 16 x `qsag_gl64_mul_slice64x4` (64b x 4b -> 68b s, c)
      * 8 x `qsag_gl64_mul_comb_l1` (shift 4, 68b -> 72b)
      * 4 x `qsag_gl64_mul_comb_l2` (shift 8, 72b -> 80b)
      * 2 x `qsag_gl64_mul_comb_l3` (shift 16, 80b -> 96b)
      * 1 x `qsag_gl64_mul_comb_l4` (shift 32, 96b -> 128b)
    """
    mods = []
    ms = Mod("qsag_gl64_mul_slice64x4", [
        "input  wire [63:0] a",
        "input  wire [3:0]  b",
        "output wire [67:0] s",
        "output wire [67:0] c",
    ])
    csa_s = Csa(ms)
    for i in range(64):
        for j in range(4):
            csa_s.raw(ms.w(f"a[{i}] & b[{j}]"), i + j)
    _assign_rows(ms, csa_s, 68)
    mods.append(ms.text())
    stats["mul_slice64x4 (fa, ha, stages)"] = (csa_s.fas, csa_s.has, csa_s.stages)

    tot_fa = 16 * csa_s.fas
    levels = [
        (1, 68, 4, 72, 8),
        (2, 72, 8, 80, 4),
        (3, 80, 16, 96, 2),
        (4, 96, 32, 128, 1),
    ]
    for lvl, win, sh, wout, count in levels:
        mc = Mod(f"qsag_gl64_mul_comb_l{lvl}", [
            f"input  wire [{win - 1}:0] s0",
            f"input  wire [{win - 1}:0] c0",
            f"input  wire [{win - 1}:0] s1",
            f"input  wire [{win - 1}:0] c1",
            f"output wire [{wout - 1}:0] s",
            f"output wire [{wout - 1}:0] c",
        ])
        cc = Csa(mc)
        for b in range(win):
            cc.raw(f"s0[{b}]", b)
            cc.raw(f"c0[{b}]", b)
            if b + sh < wout:
                cc.raw(f"s1[{b}]", b + sh)
                cc.raw(f"c1[{b}]", b + sh)
        _assign_rows(mc, cc, wout)
        mods.append(mc.text())
        tot_fa += count * cc.fas
        stats[f"mul_comb_l{lvl} (fa, ha)"] = (cc.fas, cc.has)

    stats["mul_tree_total_fa"] = tot_fa

    top = [
        "module qsag_gl64_mul_tree (",
        "  input  wire [63:0]  a,",
        "  input  wire [63:0]  b,",
        "  output wire [127:0] s,",
        "  output wire [127:0] c",
        ");",
    ]
    for k in range(16):
        top.append(f"  wire [67:0] l0_s{k}, l0_c{k};")
        top.append(f"  qsag_gl64_mul_slice64x4 u_s{k} (.a(a), .b(b[{4*k+3}:{4*k}]), .s(l0_s{k}), .c(l0_c{k}));")
    for lvl, win, sh, wout, count in levels:
        prev = f"l{lvl - 1}"
        cur = f"l{lvl}"
        for k in range(count):
            if lvl < 4:
                top.append(f"  wire [{wout - 1}:0] {cur}_s{k}, {cur}_c{k};")
                so, co = f"{cur}_s{k}", f"{cur}_c{k}"
            else:
                so, co = "s", "c"
            top.append(
                f"  qsag_gl64_mul_comb_l{lvl} u_l{lvl}_{k} ("
                f".s0({prev}_s{2*k}), .c0({prev}_c{2*k}), "
                f".s1({prev}_s{2*k+1}), .c1({prev}_c{2*k+1}), .s({so}), .c({co}));"
            )
    top.append("endmodule\n")
    return "\n".join(mods) + "\n" + "\n".join(top)


def gen_fold():
    """Two-step modular CSA fold (`fold_one` + single-pass 4-row `fold_pair`)."""
    m1 = Mod("qsag_gl64_fold_one", [
        "input  wire [127:0] v",
        "output wire [W1-1:0] x",
        "output wire [W1-1:0] y",
    ])
    c1 = Csa(m1)
    c1.term("v", 128)
    x1, y1, w1, q1 = c1.rows("r", None)
    m1.raw(f"assign x = {x1};")
    m1.raw(f"assign y = {y1};")
    m1.ports[1] = f"output wire [{w1 - 1}:0] x"
    m1.ports[2] = f"output wire [{w1 - 1}:0] y"
    stats["fold_one (W1, q1, fa)"] = (w1, q1, c1.fas)

    m2 = Mod("qsag_gl64_fold_pair", [
        f"input  wire [{w1 - 1}:0] sx",
        f"input  wire [{w1 - 1}:0] sy",
        f"input  wire [{w1 - 1}:0] cx",
        f"input  wire [{w1 - 1}:0] cy",
        "output wire [FW-1:0] x",
        "output wire [FW-1:0] y",
    ])
    c2 = Csa(m2)
    for sig in ("sx", "sy", "cx", "cy"):
        c2.term(sig, w1)
    x2, y2, fw, fq = c2.rows("r", 3)
    m2.raw(f"assign x = {x2};")
    m2.raw(f"assign y = {y2};")
    m2.ports[4] = f"output wire [{fw - 1}:0] x"
    m2.ports[5] = f"output wire [{fw - 1}:0] y"
    stats["fold_pair (FW, fq, fa)"] = (fw, fq, c2.fas)

    wrap = f"""module qsag_gl64_fold (
  input  wire [127:0] s,
  input  wire [127:0] c,
  output wire [{fw - 1}:0] x,
  output wire [{fw - 1}:0] y
);
  wire [{w1 - 1}:0] sx, sy, cx, cy;
  qsag_gl64_fold_one u_fs (.v(s), .x(sx), .y(sy));
  qsag_gl64_fold_one u_fc (.v(c), .x(cx), .y(cy));
  qsag_gl64_fold_pair u_fp (.sx(sx), .sy(sy), .cx(cx), .cy(cy), .x(x), .y(y));
endmodule
"""
    red = f"""module qsag_gl64_reduce128_csa (
  input  wire [127:0] v,
  output wire [63:0]  r
);
  wire [{w1 - 1}:0] x, y;
  qsag_gl64_fold_one u_f (.v(v), .x(x), .y(y));
  qsag_gl64_final_par #(.W({w1}), .NJ({q1 + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""
    return m1.text() + "\n" + m2.text() + "\n" + wrap, red, w1, q1, fw, fq


def gen_mul(fw, fq):
    return f"""module qsag_gl64_mul_csa (
  input  wire [63:0] a,
  input  wire [63:0] b,
  output wire [63:0] r
);
  wire [127:0] s, c;
  wire [{fw - 1}:0] x, y;
  qsag_gl64_mul_tree u_tree (.a(a), .b(b), .s(s), .c(c));
  qsag_gl64_fold u_fold (.s(s), .c(c), .x(x), .y(y));
  qsag_gl64_final_par #(.W({fw}), .NJ({fq + 1})) u_final (.x(x), .y(y), .r(r));
endmodule
"""


def _emit_lin_mod(name, terms):
    """Emit a small <=4-row linear-combination module `r = (sum_k wt_k * (in_k : W_k)) mod p`."""
    ports = [f"input  wire [{w_in - 1}:0] {sig}" for sig, w_in, _, _ in terms] + ["output wire [63:0] r"]
    m = Mod(name, ports)
    c = Csa(m)
    rows = 0
    for sig, w_in, sh, wt in terms:
        if abs(wt) == 7:
            c.term_exact(sig, w_in, sh + 3, 1 if wt > 0 else -1)
            c.term_exact(sig, w_in, sh, -1 if wt > 0 else 1)
            rows += 2
        elif wt != 0:
            c.term_exact(sig, w_in, sh, wt)
            rows += 1
    assert rows <= 4, f"{name} has {rows} CSA rows (> 4)"
    x, y, w, q = c.rows("o_", None)
    final(m, "u_f", x, y, w, q, "r", False)
    return m.text(), c.fas


def gen_ext4_karatsuba():
    """True 2-level Tower Karatsuba over F_p[v]/(v^4 - 7), limb order [1, u, v, u*v]:
      * Level 1 (3 x F_{p^2} Karatsuba): `qsag_fp2_kara_re` (`m0 + 7*m1`, 3 rows) & `qsag_fp2_kara_im` (`m2 - m0 - m1`, 3 rows)
      * Level 2 (outer Ext4 reconstruction + addend Z): `qsag_ext4_kara_r0..r3` (3-4 rows each)
    """
    inp = """module qsag_ext4_kara_inputs (
  input  wire [255:0] a,
  output wire [575:0] q
);
  wire [63:0] a0 = a[63:0];
  wire [63:0] a1 = a[127:64];
  wire [63:0] a2 = a[191:128];
  wire [63:0] a3 = a[255:192];
  wire [63:0] s01, s23, s02, s13, sall;
  qsag_gl64_addsub u_01  (.a(a0),  .b(a1),  .sub(1'b0), .r(s01));
  qsag_gl64_addsub u_23  (.a(a2),  .b(a3),  .sub(1'b0), .r(s23));
  qsag_gl64_addsub u_02  (.a(a0),  .b(a2),  .sub(1'b0), .r(s02));
  qsag_gl64_addsub u_13  (.a(a1),  .b(a3),  .sub(1'b0), .r(s13));
  qsag_gl64_addsub u_all (.a(s01), .b(s23), .sub(1'b0), .r(sall));
  assign q = {sall, s13, s02, s23, a3, a2, s01, a1, a0};
endmodule
"""
    fp2_re, fa_re = _emit_lin_mod("qsag_fp2_kara_re", [("m0", 64, 0, 1), ("m1", 64, 0, 7)])
    fp2_im, fa_im = _emit_lin_mod("qsag_fp2_kara_im", [("m2", 64, 0, 1), ("m0", 64, 0, -1), ("m1", 64, 0, -1)])
    r0, fa0 = _emit_lin_mod("qsag_ext4_kara_r0", [("re_a", 64, 0, 1), ("im_b", 64, 0, 7), ("z0", 64, 0, 1)])
    r1, fa1 = _emit_lin_mod("qsag_ext4_kara_r1", [("im_a", 64, 0, 1), ("re_b", 64, 0, 1), ("z1", 64, 0, 1)])
    r2, fa2 = _emit_lin_mod("qsag_ext4_kara_r2", [("re_m", 64, 0, 1), ("re_a", 64, 0, -1), ("re_b", 64, 0, -1), ("z2", 64, 0, 1)])
    r3, fa3 = _emit_lin_mod("qsag_ext4_kara_r3", [("im_m", 64, 0, 1), ("im_a", 64, 0, -1), ("im_b", 64, 0, -1), ("z3", 64, 0, 1)])
    stats["kara_combine_fa"] = 3 * (fa_re + fa_im) + fa0 + fa1 + fa2 + fa3

    comb = """module qsag_ext4_kara_combine (
  input  wire [575:0] p,
  input  wire [255:0] z,
  output wire [255:0] r
);
  wire [63:0] p0 = p[63:0],    p1 = p[127:64],  p2 = p[191:128];
  wire [63:0] p3 = p[255:192], p4 = p[319:256], p5 = p[383:320];
  wire [63:0] p6 = p[447:384], p7 = p[511:448], p8 = p[575:512];
  wire [63:0] z0 = z[63:0],    z1 = z[127:64],  z2 = z[191:128], z3 = z[255:192];
  wire [63:0] re_a, im_a, re_b, im_b, re_m, im_m;
  qsag_fp2_kara_re u_rea (.m0(p0), .m1(p1), .r(re_a));
  qsag_fp2_kara_im u_ima (.m2(p2), .m0(p0), .m1(p1), .r(im_a));
  qsag_fp2_kara_re u_reb (.m0(p3), .m1(p4), .r(re_b));
  qsag_fp2_kara_im u_imb (.m2(p5), .m0(p3), .m1(p4), .r(im_b));
  qsag_fp2_kara_re u_rem (.m0(p6), .m1(p7), .r(re_m));
  qsag_fp2_kara_im u_imm (.m2(p8), .m0(p6), .m1(p7), .r(im_m));
  qsag_ext4_kara_r0 u_r0 (.re_a(re_a), .im_b(im_b), .z0(z0), .r(r[63:0]));
  qsag_ext4_kara_r1 u_r1 (.im_a(im_a), .re_b(re_b), .z1(z1), .r(r[127:64]));
  qsag_ext4_kara_r2 u_r2 (.re_m(re_m), .re_a(re_a), .re_b(re_b), .z2(z2), .r(r[191:128]));
  qsag_ext4_kara_r3 u_r3 (.im_m(im_m), .im_a(im_a), .im_b(im_b), .z3(z3), .r(r[255:192]));
endmodule
"""
    return "\n".join([inp, fp2_re, fp2_im, r0, r1, r2, r3, comb])


def gen_csa_helpers():
    """Pure carry-save 3:2 and 4:2 word compressors (`sx + sy == sum(inputs)` with 0 final adders)."""
    m3 = Mod("qsag_gl64_csa3", [
        "input  wire [63:0] a0",
        "input  wire [63:0] a1",
        "input  wire [63:0] a2",
        "output wire [65:0] sx",
        "output wire [65:0] sy",
    ])
    c3 = Csa(m3)
    for k in range(3):
        c3.term_exact(f"a{k}", 64)
    _assign_rows(m3, c3, 66, "sx", "sy")

    m4 = Mod("qsag_gl64_csa4", [
        "input  wire [63:0] a0",
        "input  wire [63:0] a1",
        "input  wire [63:0] a2",
        "input  wire [63:0] a3",
        "output wire [65:0] sx",
        "output wire [65:0] sy",
    ])
    c4 = Csa(m4)
    for k in range(4):
        c4.term_exact(f"a{k}", 64)
    _assign_rows(m4, c4, 66, "sx", "sy")
    return m3.text() + "\n" + m4.text(), c3.fas, c4.fas


def gen_me(fa_csa3, fa_csa4):
    """Hierarchical CSE M_E with <=4-row leaf modules:
      * `qsag_p2_m4`: `qsag_gl64_csa4` + `4 x qsag_p2_m4_lane` (`sx + sy + bi + 2*bj`)
      * `qsag_p2_me_col`: `qsag_gl64_csa3` + `3 x qsag_p2_me_col_lane` (`sx + sy + yb + rcb`)
    """
    m4_lane, fa_m4l = _emit_lin_mod("qsag_p2_m4_lane", [
        ("sx", 66, 0, 1), ("sy", 66, 0, 1), ("bi", 64, 0, 1), ("bj", 64, 1, 1)
    ])
    me_lane, fa_mel = _emit_lin_mod("qsag_p2_me_col_lane", [
        ("sx", 66, 0, 1), ("sy", 66, 0, 1), ("yb", 64, 0, 1), ("rcb", 64, 0, 1)
    ])
    stats["me_total_fa"] = 3 * (fa_csa4 + 4 * fa_m4l) + 4 * (fa_csa3 + 3 * fa_mel)

    m4_wrap = """module qsag_p2_m4 (
  input  wire [255:0] b,
  output wire [255:0] y
);
  wire [63:0] b0 = b[63:0], b1 = b[127:64], b2 = b[191:128], b3 = b[255:192];
  wire [65:0] sx, sy;
  qsag_gl64_csa4    u_s  (.a0(b0), .a1(b1), .a2(b2), .a3(b3), .sx(sx), .sy(sy));
  qsag_p2_m4_lane   u_l0 (.sx(sx), .sy(sy), .bi(b0), .bj(b1), .r(y[63:0]));
  qsag_p2_m4_lane   u_l1 (.sx(sx), .sy(sy), .bi(b1), .bj(b2), .r(y[127:64]));
  qsag_p2_m4_lane   u_l2 (.sx(sx), .sy(sy), .bi(b2), .bj(b3), .r(y[191:128]));
  qsag_p2_m4_lane   u_l3 (.sx(sx), .sy(sy), .bi(b3), .bj(b0), .r(y[255:192]));
endmodule
"""
    mc_wrap = """module qsag_p2_me_col (
  input  wire [63:0] y0,
  input  wire [63:0] y1,
  input  wire [63:0] y2,
  input  wire [63:0] rc0,
  input  wire [63:0] rc1,
  input  wire [63:0] rc2,
  output wire [63:0] o0,
  output wire [63:0] o1,
  output wire [63:0] o2
);
  wire [65:0] sx, sy;
  qsag_gl64_csa3      u_s  (.a0(y0), .a1(y1), .a2(y2), .sx(sx), .sy(sy));
  qsag_p2_me_col_lane u_l0 (.sx(sx), .sy(sy), .yb(y0), .rcb(rc0), .r(o0));
  qsag_p2_me_col_lane u_l1 (.sx(sx), .sy(sy), .yb(y1), .rcb(rc1), .r(o1));
  qsag_p2_me_col_lane u_l2 (.sx(sx), .sy(sy), .yb(y2), .rcb(rc2), .r(o2));
endmodule
"""
    lines = [
        "module qsag_p2_me (",
        "  input  wire [767:0] x,",
        "  input  wire [767:0] rc,",
        "  output wire [767:0] y",
        ");",
        "  wire [255:0] m0, m1, m2;",
        "  qsag_p2_m4 u_m0 (.b({x[639:576], x[447:384], x[255:192], x[63:0]}),    .y(m0));",
        "  qsag_p2_m4 u_m1 (.b({x[703:640], x[511:448], x[319:256], x[127:64]}),  .y(m1));",
        "  qsag_p2_m4 u_m2 (.b({x[767:704], x[575:512], x[383:320], x[191:128]}), .y(m2));",
    ]
    for i in range(4):
        l0, l1, l2 = 3 * i, 3 * i + 1, 3 * i + 2
        lines.append(
            f"  qsag_p2_me_col u_c{i} ("
            f".y0(m0[{64*i+63}:{64*i}]), .y1(m1[{64*i+63}:{64*i}]), .y2(m2[{64*i+63}:{64*i}]), "
            f".rc0(rc[{64*l0+63}:{64*l0}]), .rc1(rc[{64*l1+63}:{64*l1}]), .rc2(rc[{64*l2+63}:{64*l2}]), "
            f".o0(y[{64*l0+63}:{64*l0}]), .o1(y[{64*l1+63}:{64*l1}]), .o2(y[{64*l2+63}:{64*l2}]));"
        )
    lines.append("endmodule\n")
    return "\n".join([m4_lane, me_lane, m4_wrap, mc_wrap, "\n".join(lines)])


def gen_mi(fa_csa3):
    """Hierarchical CSE M_I with <=4-row leaf modules:
      * `qsag_gl64_sum6`: `2 x qsag_gl64_csa3` + `qsag_gl64_sum4_csa` (4 rows)
      * `qsag_p2_mi_lane0..11`: 4 rows each
    """
    sum4_csa, fa_s4 = _emit_lin_mod("qsag_gl64_sum4_csa", [
        ("sx0", 66, 0, 1), ("sy0", 66, 0, 1), ("sx1", 66, 0, 1), ("sy1", 66, 0, 1)
    ])
    sum6_wrap = """module qsag_gl64_sum6 (
  input  wire [63:0] a0,
  input  wire [63:0] a1,
  input  wire [63:0] a2,
  input  wire [63:0] a3,
  input  wire [63:0] a4,
  input  wire [63:0] a5,
  output wire [63:0] r
);
  wire [65:0] sx0, sy0, sx1, sy1;
  qsag_gl64_csa3     u_c0 (.a0(a0), .a1(a1), .a2(a2), .sx(sx0), .sy(sy0));
  qsag_gl64_csa3     u_c1 (.a0(a3), .a1(a4), .a2(a5), .sx(sx1), .sy(sy1));
  qsag_gl64_sum4_csa u_s4 (.sx0(sx0), .sy0(sy0), .sx1(sx1), .sy1(sy1), .r(r));
endmodule
"""
    tail = """module qsag_p2_mi_tail (
  input  wire [703:0] x_hi,
  output wire [63:0]  s_tail
);
  wire [63:0] s_lo, s_hi;
  qsag_gl64_sum6 u_lo (
    .a0(x_hi[63:0]),    .a1(x_hi[127:64]),  .a2(x_hi[191:128]),
    .a3(x_hi[255:192]), .a4(x_hi[319:256]), .a5(x_hi[383:320]), .r(s_lo));
  qsag_gl64_sum6 u_hi (
    .a0(x_hi[447:384]), .a1(x_hi[511:448]), .a2(x_hi[575:512]),
    .a3(x_hi[639:576]), .a4(x_hi[703:640]), .a5(64'd0),         .r(s_hi));
  qsag_gl64_addsub u_add (.a(s_lo), .b(s_hi), .sub(1'b0), .r(s_tail));
endmodule
"""
    lanes = []
    tot_fa = 2 * (2 * fa_csa3 + fa_s4)
    for l in range(12):
        ports = ["input  wire [63:0] x0", "input  wire [63:0] s_tail", "input  wire [63:0] rcl"]
        if l > 0:
            ports.insert(1, "input  wire [63:0] xl")
        ports.append("output wire [63:0] y")
        ml = Mod(f"qsag_p2_mi_lane{l}", ports)
        cl = Csa(ml)
        cl.term_exact("s_tail", 64)
        cl.term_exact("rcl", 64)
        if l == 0:
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("x0", 64, 6, -1)
        else:
            cl.term_exact("x0", 64, 0, 1)
            cl.term_exact("xl", 64, l - 1, 1)
        lx, ly, lw, lq = cl.rows("o_", None)
        final(ml, "u_f", lx, ly, lw, lq, "y", False)
        tot_fa += cl.fas
        lanes.append(ml.text())
    stats["mi_total_fa"] = tot_fa

    app = [
        "module qsag_p2_mi_apply (",
        "  input  wire [63:0]  x0,",
        "  input  wire [703:0] x_hi,",
        "  input  wire [63:0]  s_tail,",
        "  input  wire [767:0] rc,",
        "  output wire [767:0] y",
        ");",
        "  qsag_p2_mi_lane0 u_l0 (.x0(x0), .s_tail(s_tail), .rcl(rc[63:0]), .y(y[63:0]));",
    ]
    for l in range(1, 12):
        hi_lo = 64 * (l - 1)
        app.append(
            f"  qsag_p2_mi_lane{l} u_l{l} ("
            f".x0(x0), .xl(x_hi[{hi_lo+63}:{hi_lo}]), .s_tail(s_tail), "
            f".rcl(rc[{64*l+63}:{64*l}]), .y(y[{64*l+63}:{64*l}]));"
        )
    app.append("endmodule\n")

    wrap = """module qsag_p2_mi (
  input  wire [767:0] x,
  input  wire [767:0] rc,
  output wire [767:0] y
);
  wire [63:0] s_tail;
  qsag_p2_mi_tail  u_tail  (.x_hi(x[767:64]), .s_tail(s_tail));
  qsag_p2_mi_apply u_apply (.x0(x[63:0]), .x_hi(x[767:64]), .s_tail(s_tail), .rc(rc), .y(y));
endmodule
"""
    return "\n".join([sum4_csa, sum6_wrap, tail, "\n".join(lanes), "\n".join(app), wrap])


def gen_canopy_ff():
    """ff_i = l_i + 2 r_i + 4 c_i (mod p), i < 4; l = st[0..3], r = st[4..7], c = st[8..11]."""
    m1 = Mod("qsag_p2_canopy_ff_lane", [
        "input  wire [63:0] l",
        "input  wire [63:0] r",
        "input  wire [63:0] c",
        "output wire [63:0] ff",
    ])
    csa = Csa(m1)
    csa.term_exact("l", 64, 0)
    csa.term_exact("r", 64, 1)
    csa.term_exact("c", 64, 2)
    x, y, w, q = csa.rows("o_", None)
    final(m1, "u_f", x, y, w, q, "ff", False)

    wrap = [
        "module qsag_p2_canopy_ff (",
        "  input  wire [767:0] x,",
        "  output wire [255:0] ff",
        ");",
    ]
    for i in range(4):
        wrap.append(
            f"  qsag_p2_canopy_ff_lane u_ff{i} ("
            f".l(x[{64*i+63}:{64*i}]), .r(x[{64*(4+i)+63}:{64*(4+i)}]), "
            f".c(x[{64*(8+i)+63}:{64*(8+i)}]), .ff(ff[{64*i+63}:{64*i}]));"
        )
    wrap.append("endmodule\n")
    return m1.text() + "\n" + "\n".join(wrap)


def gen_rc():
    """slot n = constants added by the linear layer that precedes S-box layer n (slot 30: none)."""
    slots = []
    for r in range(4):
        slots.append([ref.p2_rc(0, r, l) for l in range(12)])
    for r in range(22):
        slots.append([ref.p2_rc(1, r, 0)] + [0] * 11)
    for r in range(4):
        slots.append([ref.p2_rc(2, r, l) for l in range(12)])
    slots.append([0] * 12)
    out = ["module qsag_p2_rc (", "  input  wire [4:0] slot,", "  output reg  [767:0] rc", ");",
           "  always @* begin", "    case (slot)"]
    for n, s in enumerate(slots):
        val = "".join(f"{v:016x}" for v in reversed(s))
        out.append(f"      5'd{n}: rc = 768'h{val};")
    out += ["      default: rc = 768'h0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(out)


def _balanced_xor(terms):
    if not terms:
        return "1'b0"
    cur = list(terms)
    while len(cur) > 1:
        nxt = []
        for i in range(0, len(cur), 2):
            if i + 1 < len(cur):
                nxt.append(f"({cur[i]} ^ {cur[i + 1]})")
            else:
                nxt.append(cur[i])
        cur = nxt
    return cur[0]


def gen_tower_maps():
    t7, poly = ref.tower_basis()
    out = []
    for name, cols in (("qsag_tower128_to_poly", t7), ("qsag_poly_to_tower128", poly)):
        out += [f"module {name} (", "  input  wire [127:0] x,", "  output wire [127:0] y", ");"]
        for r in range(128):
            terms = [f"x[{c}]" for c in range(128) if ((cols[c] >> r) & 1)]
            out.append(f"  assign y[{r}] = {_balanced_xor(terms)};")
        out += ["endmodule", ""]
    return "\n".join(out)


