"""Rebuild the fixed RV64I control ROM. Run from the staged ASIC directory."""
import os
from pathlib import Path
import struct
import subprocess
import tempfile
import hashlib

src = Path(__file__).resolve().parent
with tempfile.TemporaryDirectory(dir=os.environ["TMPDIR"]) as tmp:
    binary = Path(tmp) / "verifier.bin"
    subprocess.run(["clang", "--target=riscv64-none-elf", "-march=rv64i", "-mabi=lp64",
                    "-Oz", "-ffreestanding", "-fno-builtin", "-fno-exceptions", "-fno-rtti",
                    "-nostdlib", "-msmall-data-limit=0", "-mno-relax", "-fuse-ld=lld",
                    "-Wl,-T," + str(src / "link.ld"), "-Wl,--oformat=binary",
                    str(src / "start.S"), str(src / "verify.cpp"), "-o", str(binary)], check=True)
    data = binary.read_bytes()
if len(data) > 32768:
    raise ValueError(f"{len(data)} firmware bytes exceed 32 KiB")
depth = 2048 if len(data) <= 16384 else 4096
aw = depth.bit_length() - 1
words = [v for (v,) in struct.iter_unpack("<Q", data.ljust(depth * 8, b"\0"))]
(src / "verifier.hex").write_text("".join(f"{v:016x}\n" for v in words))
(src.parent / "qsag_auto_rom_size.svh").write_text(
    f"// Generated by rtl/auto/build.py\nlocalparam int ROM_AW = {aw};\n")
init = "\n".join(f"      rom[{i}] = 8'(64'h{v:016x} >> (8*b));"
                 for i, v in enumerate(words))
(src.parent / "qsag_auto_rom.sv").write_text(f"""// Generated by rtl/auto/build.py. No external initialization file.
module qsag_auto_rom(input wire clk, input wire [{aw-1}:0] addr, output logic [63:0] word_o);
  // Byte slices map one block deep, without an external depth-select mux.
  for (genvar b = 0; b < 8; b++) begin : g_byte
    (* rom_style = "block", ram_style = "block" *)
    logic [7:0] rom [0:{depth-1}];
    initial begin
{init}
    end
    always_ff @(posedge clk) word_o[8*b +: 8] <= rom[addr];
  end
endmodule
""")
print(f"{len(data)} firmware bytes, {depth} x 64 ROM, SHA256 {hashlib.sha256(data).hexdigest()}")
