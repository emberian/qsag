#!/usr/bin/env python3
"""Collect synth/logs/summary.txt into synth/RESULTS.md (mapped area in kGE = cell area / NAND2 area,
ABC `stime` critical-path delay per stage and library)."""
import re
import sys
from collections import defaultdict

NAND2 = {"sky130": ("sky130_fd_sc_hd__nand2_1", 3.7536), "ihp130": ("sg13g2_nand2_1", 7.2576),
         "nangate45": ("NAND2_X1", 0.798), "asap7": ("NAND2xp5_ASAP7_75t_R", 0.05832)}
LIBS = ["sky130", "ihp130", "nangate45", "asap7"]
rows = defaultdict(dict)
top = {}
fails = []
nand = []
for line in open(sys.argv[1]):
    m = re.match(r"stage (\S+) (\S+) (\S+): exit (\d+)(?: Delay = *([\d.]+) ps)?(?: .*?: ([\d.]+))?", line)
    if m:
        name, lib, var, rc, delay, area = m.groups()
        if rc != "0" or not area:
            fails.append(f"stage {name} {lib} {var}: exit {rc}")
            continue
        rows[(name, var)][lib] = (float(delay) if delay else None, float(area))
        continue
    m = re.match(r"topfast (\S+): exit (\d+)(?: .*?: ([\d.]+))?(?: .*?: ([\d.]+))?", line)
    if m:
        lib, rc, area, seq = m.groups()
        if rc != "0" or not area:
            fails.append(f"topfast {lib}: exit {rc}")
        else:
            top[lib] = (float(area), float(seq) if seq else None)
        continue
    if line.startswith("nand "):
        nand.append(line.strip())
out = ["# QSAG-NI synthesis results (generated by synth/summarize.py from synth/logs/summary.txt)", "",
       "kGE = mapped cell area / area of the library's NAND2 (" +
       ", ".join(f"{l}: {NAND2[l][0]} = {NAND2[l][1]} um^2" for l in LIBS) + ").",
       "Delay = ABC `stime -p` of the mapped, buffered and sized netlist (no placement, no wire load).",
       "`bk` = Yosys default Brent-Kung carry networks, `ks` = Kogge-Stone (`+/choices/kogge-stone.v`).", "",
       "| module / stage | adders | " + " | ".join(f"{l} kGE" for l in LIBS) + " | " + " | ".join(f"{l} ns" for l in LIBS) + " |",
       "|---|---|" + "---:|" * (2 * len(LIBS))]
for (name, var), d in sorted(rows.items()):
    kge = [f"{d[l][1] / NAND2[l][1] / 1000:.1f}" if l in d else "-" for l in LIBS]
    ns = [f"{d[l][0] / 1000:.2f}" if l in d and d[l][0] else "-" for l in LIBS]
    out.append(f"| `{name}` | {var} | " + " | ".join(kge) + " | " + " | ".join(ns) + " |")
out += ["", "## Whole flat top (`abc -fast`, area only; SRAM macro is a black box and not counted)", "",
        "| library | cell area (um^2) | kGE | of which flip-flops (um^2) |", "|---|---:|---:|---:|"]
for l in LIBS:
    if l in top:
        out.append(f"| {l} | {top[l][0]:.0f} | {top[l][0] / NAND2[l][1] / 1000:.0f} | {top[l][1] if top[l][1] is not None else '-'} |")
out += ["", "## Generic NAND2/INV mapping (`abc -g NAND`, `stat -tech cmos`, `ltp`)", ""] + [f"- {n}" for n in nand]
out += ["", "## Jobs that did not finish inside the 600 s build cap", ""] + [f"- {f}" for f in fails or ["none"]]
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("\n".join(out))
