#!/usr/bin/env python3
"""Turn validation/tests/fixtures/lean_external_oracle_vectors.json (the kernel-checked Lean
oracle vectors of the qsag repository) into a C++ header for the Verilator testbench."""
import json, sys
d = json.load(open(sys.argv[1]))
o = ["// GENERATED by tb/gen_kat.py from lean_external_oracle_vectors.json. Do not edit.",
     "#pragma once", "#include <cstdint>", "#include <cstddef>", ""]
u = lambda s: "%dULL" % int(s)

g = d["goldilocks_edges"]
o.append("struct KatGl { uint64_t a_raw, b_raw, mul, pow7_a; };")
o.append("static const KatGl KAT_GL[] = {")
for e in g:
    o.append("  {%s, %s, %s, %s}," % (u(e["a_raw"]), u(e["b_raw"]), u(e["mul"]), u(e["pow7_a"])))
o.append("};")

o.append("struct KatExt4 { uint64_t x[4], y[4], mul[4]; };")
o.append("static const KatExt4 KAT_EXT4[] = {")
for e in d["goldilocks_ext4"]:
    f = lambda k: "{" + ", ".join(u(v) for v in e[k]) + "}"
    o.append("  {%s, %s, %s}," % (f("x"), f("y"), f("mul")))
o.append("};")

o.append("struct KatP2 { uint64_t in[12], out[12]; };")
o.append("static const KatP2 KAT_P2[] = {")
for e in d["poseidon2_12"]:
    f = lambda k: "{" + ", ".join(u(v) for v in e[k]) + "}"
    o.append("  {%s, %s}," % (f("input"), f("perm")))
o.append("};")

o.append("struct KatSponge { const char* msg; const char* sha3_256; const char* shake256_64; const char* cshake256_64; };")
o.append("static const KatSponge KAT_SPONGE[] = {")
for e in d["sponges"]:
    o.append('  {"%s", "%s", "%s", "%s"},' % (e["msg_hex"], e["sha3_256_hex"], e["shake256_64_hex"], e["cshake256_64_hex"]))
o.append("};")
o.append('static const char KAT_CSHAKE_CUSTOM[] = "QSAG.EXTERNAL.SPEC";')
o.append("struct KatTower { uint64_t a[2], b[2], mul[2], inv[2]; };")
o.append("static const KatTower KAT_TOWER[] = {")
for e in d['tower128']:
    vals=[]
    for key in ['a_le_hex','b_le_hex','mul_le_hex','inv_a_le_hex']:
        v=int.from_bytes(bytes.fromhex(e[key]),'little')
        vals.append("{"+u(v & (2**64-1))+", "+u(v>>64)+"}")
    o.append("  {"+", ".join(vals)+"},")
o.append("};")
open(sys.argv[2], "w").write("\n".join(o) + "\n")
