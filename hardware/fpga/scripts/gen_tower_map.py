#!/usr/bin/env python3
"""Derive the exact qsag-asm Wiedemann isomorphism, checking defining equations.
Run from hardware/fpga, optionally passing a qsag repository root.
"""
from pathlib import Path
import re, sys, json
ROOT = Path(__file__).resolve().parents[1]
repo = Path(sys.argv[1]) if len(sys.argv)>1 else ROOT.parents[1]
MASK=(1<<128)-1

def mul(a,b):
    r=0
    for _ in range(128):
        if b&1: r ^= a
        b >>= 1
        a=(a<<1)^ (0x87 if a>>127 else 0)
        a &= MASK
    return r

def apply(cols,x):
    v=0
    for i,c in enumerate(cols):
        if x>>i&1: v ^= c
    return v

def matrices(repo):
    text=(repo/'crates/qsag-asm/src/portable.rs').read_text()
    body=text.split('pub const TOWER128_POLY_GENERATORS:')[1].split('= [')[1].split('];')[0]
    gs=[int(x.replace('_',''),16) for x in re.findall(r'0x[0-9a-f_]+',body)]
    assert len(gs)==7
    for i,g in enumerate(gs): assert mul(g,g)^mul(gs[i-1] if i else 1,g)==1
    cols=[]
    for i in range(128):
        v=1
        for j,g in enumerate(gs):
            if i>>j&1: v=mul(v,g)
        cols.append(v)
    rows=[sum(((c>>i)&1)<<j for j,c in enumerate(cols)) for i in range(128)]
    lhs=rows[:]; rhs=[1<<i for i in range(128)]
    for i in range(128):
        k=next(k for k in range(i,128) if lhs[k]>>i&1)
        lhs[i],lhs[k]=lhs[k],lhs[i]; rhs[i],rhs[k]=rhs[k],rhs[i]
        for j in range(128):
            if j!=i and lhs[j]>>i&1: lhs[j]^=lhs[i]; rhs[j]^=rhs[i]
    invcols=[sum(((r>>i)&1)<<j for j,r in enumerate(rhs)) for i in range(128)]
    assert all(apply(invcols,c)==1<<i for i,c in enumerate(cols))
    return rows,rhs,cols,invcols,gs

if __name__=='__main__':
    rows,inv,cols,ic,gs=matrices(repo)
    out=['// Generated by scripts/gen_tower_map.py from qsag-asm Artin-Schreier roots.',
         '// Combinational GF(2)-linear map. INVERSE=0: tower -> polynomial; 1: reverse.',
         'module qsag_gf128_tower_map #(parameter bit INVERSE = 0) (',
         '    input logic [127:0] x, output logic [127:0] y', ');',
         '    if (INVERSE) begin : g_inverse']
    for i,r in enumerate(inv): out.append(f"        assign y[{i}] = ^(x & 128'h{r:032x});")
    out.append('    end else begin : g_forward')
    for i,r in enumerate(rows): out.append(f"        assign y[{i}] = ^(x & 128'h{r:032x});")
    out += ['    end','endmodule','']
    (ROOT/'rtl/qsag_gf128_tower_map.sv').write_text('\n'.join(out))
    fixture=json.loads((repo/'validation/tests/fixtures/lean_external_oracle_vectors.json').read_text())
    for k in fixture['tower128']:
        a,b,c,iv=[int.from_bytes(bytes.fromhex(k[x]),'little') for x in ['a_le_hex','b_le_hex','mul_le_hex','inv_a_le_hex']]
        assert apply(ic,mul(apply(cols,a),apply(cols,b)))==c
        assert not a or apply(ic,mul(apply(cols,a),apply(cols,iv)))==1
    print('tower matrix: 7 defining equations, rank 128, inverse, 4 Lean products/inverses PASS')
