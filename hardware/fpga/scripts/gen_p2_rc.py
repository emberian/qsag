#!/usr/bin/env python3
"""Emit rtl/qsag_p2_rc.sv from the canonical round-constant tables of
crates/qsag-accel/shaders/poseidon2_perm12.comp (text transform only).

The table is indexed by ring pass (0..30) and holds the constants added *after*
the linear layer of that pass, i.e. the constants of the following round:
  pass 0      : initial M_E                    -> RC_EXT_INIT[0]
  pass 1..4   : initial external rounds        -> RC_EXT_INIT[1..3], then RC_INT[0] (lane 0)
  pass 5..26  : internal rounds                -> RC_INT[1..21], then RC_EXT_TERM[0]
  pass 27..30 : terminal external rounds       -> RC_EXT_TERM[1..3], then zero
"""
import re, sys
src = open(sys.argv[1]).read()
def table(name, n):
    m = re.search(name + r"\[\d+\] = uint64_t\[\d+\]\((.*?)\);", src, re.S)
    v = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{16})ul", m.group(1))]
    assert len(v) == n, (name, len(v))
    return v
ei, ri, et = table("RC_EXT_INIT", 48), table("RC_INT", 22), table("RC_EXT_TERM", 48)
rows = []
for p in range(31):
    if p <= 3:    r = ei[12*p:12*p+12]
    elif p <= 25: r = [ri[p-4]] + [0]*11
    elif p <= 29: r = et[12*(p-26):12*(p-26)+12]
    else:         r = [0]*12
    rows.append(r)
out = ["// GENERATED by scripts/gen_p2_rc.py from crates/qsag-accel/shaders/poseidon2_perm12.comp.",
       "// Do not edit. rc[64*i +: 64] is the constant added to lane i after the linear layer of `pass`.",
       "module qsag_p2_rc (", "    input  logic [4:0]   pass,", "    output logic [767:0] rc", ");",
       "    always_comb begin", "        case (pass)"]
for p, r in enumerate(rows):
    body = ", ".join("64'h%016X" % x for x in reversed(r))
    out.append("            5'd%d: rc = {%s};" % (p, body))
out += ["            default: rc = 768'd0;", "        endcase", "    end", "endmodule", ""]
open(sys.argv[2], "w").write("\n".join(out))
