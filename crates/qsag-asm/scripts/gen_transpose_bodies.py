#!/usr/bin/env python3
"""Generate the unrolled 64x256 bit-matrix transpose kernel bodies.

The transpose is the classic six-stage shift-and-mask butterfly. Stage `j` (32, 16, ..., 1)
exchanges, for every row `k` with `k & j == 0`, the bits of row `k` selected by `mask << j`
with the bits of row `k + j` selected by `mask`. Rows are 256 bits wide (four independent
64-bit columns), so one call transposes four 64x64 bit matrices at once.

Every address is `base + immediate`, every shift count is an immediate, and the only branch is
one bottom-tested loop per stage over a public block count, which is what
`audit_elf_ct.py` accepts. The bodies carry no symbol header: the Rust side prepends the
target-specific header and appends the footer.

Usage: gen_transpose_bodies.py <output-dir>
"""

import sys
from pathlib import Path

STAGES = [
    (32, 0x00000000FFFFFFFF),
    (16, 0x0000FFFF0000FFFF),
    (8, 0x00FF00FF00FF00FF),
    (4, 0x0F0F0F0F0F0F0F0F),
    (2, 0x3333333333333333),
    (1, 0x5555555555555555),
]
ROW_BYTES = 32
ROWS = 64


def x86_body() -> str:
    out = [
        "// Generated by scripts/gen_transpose_bodies.py; do not edit by hand.",
        "// rdi = rows: *mut [[u64; 4]; 64]. Clobbers rax, rcx, ymm0..ymm3.",
    ]
    for j, mask in STAGES:
        blocks = ROWS // (2 * j)
        out.append(f"mov rax, 0x{mask:016X}")
        out.append("vmovq xmm3, rax")
        out.append("vpbroadcastq ymm3, xmm3")
        out.append(f"mov ecx, {blocks}")
        out.append("2:")
        for k in range(j):
            lo = ROW_BYTES * k
            hi = ROW_BYTES * (k + j)
            out += [
                f"vmovdqu ymm0, ymmword ptr [rdi + {lo}]",
                f"vmovdqu ymm1, ymmword ptr [rdi + {hi}]",
                f"vpsrlq ymm2, ymm0, {j}",
                "vpxor ymm2, ymm2, ymm1",
                "vpand ymm2, ymm2, ymm3",
                "vpxor ymm1, ymm1, ymm2",
                f"vpsllq ymm2, ymm2, {j}",
                "vpxor ymm0, ymm0, ymm2",
                f"vmovdqu ymmword ptr [rdi + {lo}], ymm0",
                f"vmovdqu ymmword ptr [rdi + {hi}], ymm1",
            ]
        out.append(f"add rdi, {2 * j * ROW_BYTES}")
        out.append("dec rcx")
        out.append("jnz 2b")
        out.append(f"sub rdi, {ROWS * ROW_BYTES}")
    out += [
        "vpxor xmm0, xmm0, xmm0",
        "vpxor xmm1, xmm1, xmm1",
        "vpxor xmm2, xmm2, xmm2",
        "vpxor xmm3, xmm3, xmm3",
        "xor eax, eax",
        "vzeroupper",
        "ret",
    ]
    return "\n".join(out) + "\n"


def a64_body() -> str:
    out = [
        "// Generated by scripts/gen_transpose_bodies.py; do not edit by hand.",
        "// x0 = rows: *mut [[u64; 4]; 64]. Clobbers x1, x9, x10, v0..v3, v7, v16, v17.",
    ]
    for j, mask in STAGES:
        blocks = ROWS // (2 * j)
        out.append(f"    mov x9, #0x{mask:016X}")
        out.append("    dup v7.2d, x9")
        out.append(f"    mov x1, #{blocks}")
        out.append("1:")
        out.append(f"    add x10, x0, #{j * ROW_BYTES}")
        for k in range(j):
            off = ROW_BYTES * k
            out += [
                f"    ldp q0, q1, [x0, #{off}]",
                f"    ldp q2, q3, [x10, #{off}]",
                f"    ushr v16.2d, v0.2d, #{j}",
                f"    ushr v17.2d, v1.2d, #{j}",
                "    eor v16.16b, v16.16b, v2.16b",
                "    eor v17.16b, v17.16b, v3.16b",
                "    and v16.16b, v16.16b, v7.16b",
                "    and v17.16b, v17.16b, v7.16b",
                "    eor v2.16b, v2.16b, v16.16b",
                "    eor v3.16b, v3.16b, v17.16b",
                f"    shl v16.2d, v16.2d, #{j}",
                f"    shl v17.2d, v17.2d, #{j}",
                "    eor v0.16b, v0.16b, v16.16b",
                "    eor v1.16b, v1.16b, v17.16b",
                f"    stp q0, q1, [x0, #{off}]",
                f"    stp q2, q3, [x10, #{off}]",
            ]
        out.append(f"    add x0, x0, #{2 * j * ROW_BYTES}")
        out.append("    subs x1, x1, #1")
        out.append("    b.ne 1b")
        out.append(f"    sub x0, x0, #{ROWS * ROW_BYTES}")
    for reg in (0, 1, 2, 3, 7, 16, 17):
        out.append(f"    eor v{reg}.16b, v{reg}.16b, v{reg}.16b")
    out += ["    mov x9, #0", "    mov x10, #0", "    ret"]
    return "\n".join(out) + "\n"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    out_dir = Path(sys.argv[1])
    (out_dir / "x86_64_transpose64x256.s").write_text(x86_body())
    (out_dir / "aarch64_transpose64x256.s").write_text(a64_body())
    return 0


if __name__ == "__main__":
    sys.exit(main())
