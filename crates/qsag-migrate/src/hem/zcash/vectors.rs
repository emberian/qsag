use std::vec::Vec;

/// Decode a hex string.
pub fn unhex(s: &str) -> Vec<u8> {
    (0..s.len() / 2)
        .map(|i| u8::from_str_radix(&s[2 * i..2 * i + 2], 16).expect("hex"))
        .collect()
}

/// Decode a 32-byte hex string.
pub fn hex32(s: &str) -> [u8; 32] {
    unhex(s).try_into().expect("32 bytes")
}

