#!/usr/bin/env python3
"""Microcode ROM image of the model, as synthesizable SystemVerilog and as a text file.

    python3 gen_rom.py [--scratch N] <S|L> <out.sv> [<out.txt>]

dregg_urom (the .sv) is three case tables (words, 64-bit constants, opcode dispatch) and two constants
(image length, words used). Addresses outside the image read as the trap word ILL. The text file is the
form the co-simulation bench loads (rom_text below).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "rtl")))
import gen_defs  # noqa: E402


def rom_text(rom):
    o = [f"LEN {len(rom.words)} USED {rom.used}"]
    o.append("W " + " ".join(f"{w:07x}" for w in rom.words))
    o.append("C " + " ".join(f"{c:016x}" for c in rom.consts))
    o.append("D " + " ".join(f"{op:x}:{addr:x}:{cls:x}" for op, (addr, cls) in sorted(rom.entries.items())))
    return "\n".join(o) + "\n"


def rom_sv(rom, isa, name="dregg_urom"):
    ill = isa.encode(isa.OP["ILL"])
    o = []
    p = o.append
    p("// Generated by v2/tb/gen_rom.py from the model's assembler output. Do not edit.")
    p(f"// {len(rom.words)} words ({rom.used} used), {len(rom.consts)} constants, {len(rom.entries)} dispatch entries.")
    p("`default_nettype none")
    p(f"module {name} (")
    p("    input  wire  [10:0] rom_addr,\n    output logic [27:0] rom_word,")
    p("    input  wire  [6:0]  const_idx,\n    output logic [63:0] const_data,\n    output logic        const_ok,")
    p("    input  wire  [7:0]  disp_op,\n    output logic        disp_hit,\n    output logic [10:0] disp_addr,")
    p("    output logic [1:0]  disp_class,\n    output wire  [11:0] rom_len,\n    output wire  [11:0] rom_used\n);")
    p(f"    assign rom_len  = 12'd{len(rom.words)};")
    p(f"    assign rom_used = 12'd{rom.used};")
    p("    always_comb begin\n        unique case (rom_addr)")
    for a, w in enumerate(rom.words):
        if w != ill:
            p(f"            11'd{a}: rom_word = 28'h{w:07x};")
    p(f"            default: rom_word = 28'h{ill:07x};")
    p("        endcase\n    end")
    p("    always_comb begin\n        const_ok = 1'b1;\n        unique case (const_idx)")
    for i, c in enumerate(rom.consts):
        p(f"            7'd{i}: const_data = 64'h{c:016x};")
    p("            default: begin const_data = 64'd0; const_ok = 1'b0; end")
    p("        endcase\n    end")
    p("    always_comb begin\n        disp_hit = 1'b1;\n        unique case (disp_op)")
    for op, (addr, cls) in sorted(rom.entries.items()):
        p(f"            8'h{op:02x}: begin disp_addr = 11'd{addr}; disp_class = 2'd{cls}; end")
    p("            default: begin disp_hit = 1'b0; disp_addr = 11'd0; disp_class = 2'd0; end")
    p("        endcase\n    end")
    p("endmodule\n`default_nettype wire")
    return "\n".join(o) + "\n"


def main():
    args = sys.argv[1:]
    scratch = None
    if args and args[0] == "--scratch":
        scratch = int(args[1])
        args = args[2:]
    if len(args) not in (2, 3):
        raise SystemExit(__doc__)
    isa = gen_defs.model_isa(scratch)
    import chip
    import romcheck
    rom = chip.build_rom(args[0])
    findings = romcheck.check(rom, romcheck.load_manifest())
    if findings:
        raise SystemExit("gen_rom: romcheck findings:\n" + "\n".join(findings))
    with open(args[1], "w") as fh:
        fh.write(rom_sv(rom, isa))
    if len(args) == 3:
        with open(args[2], "w") as fh:
            fh.write(rom_text(rom))
    print(f"gen_rom: {len(rom.words)} words, {rom.used} used, {len(rom.consts)} constants, {len(rom.entries)} entries")


if __name__ == "__main__":
    main()
